import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_lint_multidriven_relay_scale.v"

# A chain of output ports driven only by z, connected to a net with another driver
SIZE_RATIO = 4
SIZE_SMALL = 128
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_lint_multidriven_relay_scale.py\n")
        fh.write("module r0 (output wire o);\n  assign o = 1'bz;\nendmodule\n")
        for i in range(1, n + 1):
            fh.write(f"module r{i} (output wire o);\n  r{i - 1} c (.o);\nendmodule\n")
        fh.write(f"module t (output wire o);\n  r{n} c (.o);\n  assign o = 1'b1;\nendmodule\n")


def lint(n):
    gen(test.top_filename, n)
    test.lint(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"])
    return test.op_count_read(test.stats)


test.op_count_ok(lint(SIZE_SMALL), lint(SIZE_LARGE), RATIO_MIN, RATIO_MAX, r'.*')

test.passes()
