import re

import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_asan or test.tsan:
    test.skip("Too deep a call chain for the stack with sanitizers")

test.top_filename = test.obj_dir + "/t_property_local_var_call_chain.v"

# A chain of functions, each calling the previous, with a property calling each, found from the
# last function of the chain
N_FUNCS = 4000
# The work of finding what the values do, linear in the functions and calls
MAX_WORK = 30 * N_FUNCS


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_property_local_var_call_chain.py\n")
        fh.write("module t (input clk, input int x);\n")
        for i in range(N_FUNCS):
            body = f"f{i - 1}(n)" if i else "n"
            fh.write(f"  function automatic int f{i}(int n);\n")
            fh.write("    /* verilator no_inline_task */\n")
            fh.write(f"    return {body};\n")
            fh.write("  endfunction\n")
        for i in reversed(range(N_FUNCS)):
            fh.write(f"  property p{i};\n")
            fh.write("    int v;\n")
            fh.write(f"    @(posedge clk) (1, v = f{i}(x)) |-> (v == x);\n")
            fh.write("  endproperty\n")
            fh.write(f"  assert property (p{i});\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--assert"])

stats = test.file_contents(test.stats)
work = re.search(r'Assertions, local variable lowering work\s+(\d+)', stats)
if not work:
    test.error("Lowering work not found in " + test.stats)
if int(work.group(1)) > MAX_WORK:
    test.error(f"Lowering work {work.group(1)} with {N_FUNCS} functions (over {MAX_WORK})")

test.passes()
