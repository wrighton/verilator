import re

import vltest_bootstrap

test.scenarios('linter')

test.top_filename = test.obj_dir + "/" + test.name + ".sv"

# Scopes wildcard importing many packages, and looking up many names in them. Checks the
# number of name lookups in packages, and of entries in indexes of the packages' names, which
# should be about linear in the number of packages, names and references.
N_PACKAGES = 64
N_PARAMS = 10


def stat(name):
    with open(test.stats, 'r', encoding="utf8") as fh:
        match = re.search(r'LinkDot, ' + name + r'\s+(\d+)', fh.read())
    if not match:
        test.error("LinkDot, " + name + " not found in " + test.stats)
        return 0
    return int(match.group(1))


def lint(generator, n):
    generator(test.top_filename, n)
    test.lint(verilator_flags2=["--stats", "--no-debug-check"])


def check_max(name, value, limit, what):
    if value > limit:
        test.error(f"{name} {value} is over {limit} for {what}")


def gen_vars(filename, n):
    # A module wildcard importing packages and declaring variables, each declaration looking its
    # name up in the imported packages
    last = N_PACKAGES - 1
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        for k in range(N_PACKAGES):
            fh.write(f"package p{k};\n")
            for i in range(N_PARAMS):
                fh.write(f"  localparam int c{k}_{i} = {k * N_PARAMS + i};\n")
            fh.write("endpackage\n")
        # Has c0_1 imported, but not exported, so a wildcard import of q does not import it
        fh.write("package q;\n")
        fh.write("  import p0::c0_1;\n")
        fh.write("  import p1::*;\n")
        fh.write("  localparam int qv = c0_1 + c1_2;\n")
        fh.write("endpackage\n")
        fh.write("module t;\n")
        fh.write("  import q::*;\n")
        for k in range(N_PACKAGES):
            fh.write(f"  import p{k}::*;\n")
        for i in range(n):
            if i < N_PACKAGES * N_PARAMS:  # Reference each package item once
                fh.write(f"  wire [31:0] v{i} = c{i % N_PACKAGES}_{i // N_PACKAGES};\n")
            else:
                fh.write(f"  logic v{i};\n")
        fh.write(f"  localparam int r = c0_1 + c{last}_{N_PARAMS - 1} + qv;\n")
        expected = 1 + last * N_PARAMS + N_PARAMS - 1 + 1 + N_PARAMS + 2
        fh.write(f"  if (r != {expected}) $error(\"Bad r\");\n")
        fh.write("endmodule\n")


def gen_hidden(filename, n):
    # Names imported but not exported by an early package, and exported by a late one
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("package origin;\n")
        for i in range(n):
            fh.write(f"  localparam int x{i} = {i + 1};\n")
        fh.write("endpackage\n")
        fh.write("package hidden;\n")
        for i in range(n):
            fh.write(f"  import origin::x{i};\n")
        fh.write("endpackage\n")
        for k in range(n):
            fh.write(f"package h{k};\n  localparam int y{k} = {k + 1};\nendpackage\n")
        fh.write("module t;\n")
        fh.write("  import hidden::*;\n")
        for k in range(n):
            fh.write(f"  import h{k}::*;\n")
        fh.write("  import origin::*;\n")
        for i in range(n):
            fh.write(f"  localparam int r{i} = x{i};\n")
        fh.write(f"  if (r0 + r{n - 1} != {n + 1}) $error(\"Bad r\");\n")
        fh.write("endmodule\n")


def gen_interleaved(filename, n):
    # Wildcard imports each followed by declarations
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        for k in range(n):
            fh.write(f"package i{k};\n  localparam int z{k} = {k};\nendpackage\n")
        fh.write("module t;\n")
        for k in range(n):
            fh.write(f"  import i{k}::*;\n")
            for j in range(4):
                fh.write(f"  logic f{k}_{j};\n")
        fh.write(f"  if (z{n - 1} != {n - 1}) $error(\"Bad z\");\n")
        fh.write("endmodule\n")


def gen_modules(filename, n):
    # Modules wildcard importing the same packages, which share one index
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        for k in range(8):
            fh.write(f"package s{k};\n")
            for i in range(N_PARAMS):
                fh.write(f"  localparam int d{k}_{i} = {i};\n")
            fh.write("endpackage\n")
        for m in range(n):
            fh.write(f"module m{m} (output int o);\n")
            for k in range(8):
                fh.write(f"  import s{k}::*;\n")
            for i in range(100):
                fh.write(f"  logic w{i};\n")
            fh.write(f"  assign o = d{m % 8}_{m % N_PARAMS};\n")
            fh.write("endmodule\n")
        fh.write(f"module t (output int o[{n}]);\n")
        for m in range(n):
            fh.write(f"  m{m} u{m} (.o(o[{m}]));\n")
        fh.write("endmodule\n")


# Each LinkDot run (there are two) counts its own lookups and entries
N_VARS = 20000
lint(gen_vars, N_VARS)
check_max("Package lookups", stat("Wildcard import package lookups"),
          4 * (N_VARS + N_PACKAGES * N_PARAMS), "variables")

N_HIDDEN = 1024
lint(gen_hidden, N_HIDDEN)
check_max("Package lookups", stat("Wildcard import package lookups"), 16 * N_HIDDEN,
          "hidden names")

N_INTERLEAVED = 512
lint(gen_interleaved, N_INTERLEAVED)
check_max("Index entries", stat("Wildcard import index entries peak"), 4 * N_INTERLEAVED,
          "interleaved imports")

lint(gen_modules, 50)
# One index per LinkDot run, not one per module
if stat("Wildcard import indexes") != 2:
    test.error("Expected 2 wildcard import indexes, got " + str(stat("Wildcard import indexes")))

test.passes()
