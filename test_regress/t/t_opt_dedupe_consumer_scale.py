import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_opt_dedupe_consumer_scale.v"

# Flops r<i> all assigning the same right-hand side, and flops s<i> reading them, deduped once
# the r<i> are. V3Gate dedupes all but one of each, and replaces them in one large consumer
# each: the output concatenation, and logic reaching no output. The model is not built.
N_FLOPS = 8000
# Share of verilation time spent in V3Gate (about 0.05 when linear, 0.55 when quadratic)
MAX_SHARE = 0.2
# Ignore a high share of a short time, e.g. from a load spike (quadratic takes about 2.5 s)
MIN_SECONDS = 0.5


def gen(filename):
    rs = ",\n    ".join(f"r{i}" for i in range(N_FLOPS))
    ss = ",\n    ".join(f"s{i}" for i in range(N_FLOPS))
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_opt_dedupe_consumer_scale.py\n")
        fh.write(f"module t (input clk, input d, input e, output [{N_FLOPS - 1}:0] q);\n")
        for i in range(N_FLOPS):
            fh.write(f"  logic r{i}, s{i};\n")
            fh.write(f"  always_ff @(posedge clk) r{i} <= d;\n")
            fh.write(f"  always_ff @(posedge clk) s{i} <= r{i} & e;\n")
        fh.write(f"  assign q = {{{ss}}};\n")
        fh.write(f"  always @(posedge clk) if ({{{rs}}} == 0) $display(\"zero\");\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.compile(verilator_flags2=["--stats", "--no-debug-check"],
             make_main=False,
             verilator_make_gmake=False)

test.file_grep(test.stats, r'Optimizations, Gate sigs deduped\s+(\d+)', 2 * (N_FLOPS - 1))
stats = test.file_contents(test.stats)
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
gate = re.findall(r'Stage, Elapsed time \(sec\), \d+_gate\s+(\S+)', stats)
if not total or not gate:
    test.error("Stage elapsed times not found in " + test.stats)
seconds = sum(float(t) for t in gate)
share = seconds / float(total.group(1))
if seconds > MIN_SECONDS and share > MAX_SHARE:
    test.error(f"V3Gate took {share:.0%} of verilation time with {N_FLOPS} flops (over " +
               f"{MAX_SHARE:.0%})")

test.passes()
