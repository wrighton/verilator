import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_case_return_chain_scale.v"

# Case items in each of two functions, one returning, one assigning in each item.
# Only measures V3Const time, the model is not built.
SIZE_SMALL = 1000
SIZE_LARGE = SIZE_SMALL * 4
# Linear scaling gives 4x, quadratic gives 16x
MAX_RATIO = 8
# Ignore the ratio when V3Const is fast enough that timer noise dominates
MIN_SECONDS = 0.25


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_case_return_chain_scale.py\n")
        fh.write("module t (input int x, output int y);\n")
        fh.write("  function automatic int f_return(int sel);\n")
        fh.write("    case (sel)\n")
        for i in range(n):
            fh.write(f"      {i * 7}: return {i + 1};\n")
        fh.write("      default: return 0;\n")
        fh.write("    endcase\n")
        fh.write("  endfunction\n")
        fh.write("  function automatic int f_assign(int sel);\n")
        fh.write("    int r;\n")
        fh.write("    case (sel)\n")
        for i in range(n):
            fh.write(f"      {i * 7}: r = {i + 1};\n")
        fh.write("      default: r = 0;\n")
        fh.write("    endcase\n")
        fh.write("    return r;\n")
        fh.write("  endfunction\n")
        fh.write("  assign y = f_return(x) + f_assign(x);\n")
        fh.write("endmodule\n")


def const_seconds(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    with open(test.stats, 'r', encoding="utf8") as fh:
        times = re.findall(r'Stage, Elapsed time \(sec\), \d+_const\s+(\S+)', fh.read())
    if not times:
        test.error("Const elapsed time not found in " + test.stats)
    return sum(float(t) for t in times)


small = const_seconds(SIZE_SMALL)
large = const_seconds(SIZE_LARGE)
if large > MIN_SECONDS and large > small * MAX_RATIO:
    test.error("V3Const time scaled superlinearly with case items: " +
               f"{SIZE_SMALL} items took {small:.3f}s, " +
               f"{SIZE_LARGE} items took {large:.3f}s (over {MAX_RATIO}x)")

test.passes()
