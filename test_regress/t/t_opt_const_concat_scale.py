import re

import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")
if test.have_dev_asan or test.tsan:
    test.skip("Too slow with sanitizers")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# A signal of 2*n bits with every other bit assigned zero, which DFG makes one long concatenation
# that V3Const turns into a chain of Extends, and n/4 nested signed casts, which make a chain of
# ExtendSs. The small model is also built and checked.
SIZE_SMALL = 2000
SIZE_LARGE = SIZE_SMALL * 4
# Linear scaling gives 4x, quadratic gives 16x
MAX_RATIO = 8
# Ignore the ratio when V3Const is fast enough that timer noise dominates
MIN_SECONDS = 0.5


def gen(filename, n):
    m = n // 4
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"""// Generated by {test.name}.py
// verilog_format: off
`define stop $stop
`define checkh(gotv,expv) do if ((gotv) !== (expv)) begin $write("%%Error: %s:%0d:  got='h%x exp='h%x\\n", `__FILE__,`__LINE__, (gotv), (expv)); `stop; end while(0);
// verilog_format: on
module t (
    input clk
);
  int cyc = 0;
  logic [63:0] crc = 64'h5aef0c8d_d70a4497;
  logic [{n - 1}:0] a = '0;
  logic [{n - 1}:0] b = '0;
  wire [{2 * n - 1}:0] o;
  for (genvar i = 0; i < {n}; ++i) begin : g
    assign o[2 * i] = a[i] & b[i];
    assign o[2 * i + 1] = 1'b0;
  end
""")
        fh.write(f"""  always @(posedge clk) begin
    cyc <= cyc + 1;
    crc <= {{crc[62:0], crc[63] ^ crc[2] ^ crc[0]}};
    a <= {{a[{n - 65}:0], crc}};
    b <= {{b[{n - 65}:0], ~crc ^ {{crc[31:0], crc[63:32]}}}};
    for (int i = 0; i < {n}; ++i) begin
      `checkh(o[2 * i+:2], {{1'b0, a[i] & b[i]}});
    end
    if (cyc == 99) begin
      $write("*-* All Finished *-*\\n");
      $finish;
    end
  end
""")
        for i in range(1, m + 1):
            fh.write(f"  typedef logic signed [{i}:0] s{i}_t;\n")
        fh.write(f"  wire signed [{m}:0] s =\n")
        for i in range(m, 1, -1):
            fh.write(f"    s{i}_t'(\n")
        fh.write("    s1_t'({2{\n")
        # A balanced tree, as a long chain overflows the stack of debug builds elsewhere
        terms = [f"    a[{i}]" for i in range(m)]
        while len(terms) > 1:
            terms = [
                f"({terms[i]} ^\n{terms[i + 1]})" if i + 1 < len(terms) else terms[i]
                for i in range(0, len(terms), 2)
            ]
        fh.write(terms[0])
        fh.write("\n    }})" + ")" * (m - 1) + ";\n")
        fh.write(f"""  always @(posedge clk) begin
    `checkh(s, {{{m + 1}{{^a[{m - 1}:0]}}}});
  end
endmodule
""")


def const_seconds(n, build):
    gen(test.top_filename, n)
    if build:
        test.compile(verilator_flags2=["--stats", "--no-debug-check"])
        test.execute()
    else:
        test.compile(verilator_flags2=["--stats", "--no-debug-check"],
                     make_main=False,
                     verilator_make_gmake=False)
    with open(test.stats, 'r', encoding="utf8") as fh:
        times = re.findall(r'Stage, Elapsed time \(sec\), \d+_const\s+(\S+)', fh.read())
    if not times:
        test.error("Const elapsed time not found in " + test.stats)
    return sum(float(t) for t in times)


small = const_seconds(SIZE_SMALL, True)
large = const_seconds(SIZE_LARGE, False)
if large > MIN_SECONDS and large > small * MAX_RATIO:
    test.error("V3Const time scaled superlinearly with chain length: " +
               f"n={SIZE_SMALL} took {small:.3f}s, " +
               f"n={SIZE_LARGE} took {large:.3f}s (over {MAX_RATIO}x)")

test.passes()
