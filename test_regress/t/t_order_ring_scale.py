import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_order_ring_scale.v"

# Registers in a ring, each also reading one other register, so ordering cuts many loops of
# soft edges. Only measures scheduling time, the model is not built.
SIZE_SMALL = 4000
SIZE_LARGE = SIZE_SMALL * 4
# Linear scaling gives 4x, quadratic gives 16x. Here scheduling grows about 7x (opt build), as
# cutting loops still grows about as N^1.6 on this design; quadratic ranking or placement grows
# over 40x.
MAX_RATIO = 16
# Ignore the ratio when scheduling is fast enough that timer noise dominates
MIN_SECONDS = 0.25


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_order_ring_scale.py\n")
        fh.write("module t (input clk, input int d, output int q);\n")
        for i in range(n):
            fh.write(f"  int r{i};\n")
        fh.write(f"  always_ff @(posedge clk) r0 <= r{n - 1} ^ d;\n")
        for i in range(1, n):
            fh.write(f"  always_ff @(posedge clk) r{i} <= r{i - 1} ^ r{(7 * i + 1) % n} ^ {i};\n")
        fh.write(f"  assign q = r{n - 1};\n")
        fh.write("endmodule\n")


def sched_seconds(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    with open(test.stats, 'r', encoding="utf8") as fh:
        times = re.findall(r'Stage, Elapsed time \(sec\), \d+_sched-create-\w+\s+(\S+)', fh.read())
    if not times:
        test.error("Scheduling elapsed time not found in " + test.stats)
    return sum(float(t) for t in times)


small = sched_seconds(SIZE_SMALL)
large = sched_seconds(SIZE_LARGE)
if large > MIN_SECONDS and large > small * MAX_RATIO:
    test.error("Scheduling time scaled superlinearly with ring registers: " +
               f"{SIZE_SMALL} registers took {small:.3f}s, " +
               f"{SIZE_LARGE} registers took {large:.3f}s (over {MAX_RATIO}x)")

test.passes()
