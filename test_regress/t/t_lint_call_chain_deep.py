import os
import re

import vltest_bootstrap

test.scenarios('vltmt')

# Sanitizer and debug compiler stack frames are larger, so other passes recursing along the call
# chain overflow
if (test.have_dev_asan or test.tsan
        or re.search(r'--debug(\s|$)', ' '.join(test.driver_verilator_flags))
        or os.environ.get('VERILATOR_BIN', '').endswith('_dbg')):
    test.skip("Too deep with sanitizers or the debug compiler")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# Each method calls the next one, in a chain of calls longer than recursion along it can go on the
# default stack
N_CHAIN = 20000


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        for i in reversed(range(N_CHAIN)):
            fh.write(f"class C{i};\n")
            fh.write("  int v;\n")
            if i + 1 < N_CHAIN:
                fh.write(f"  C{i + 1} nxt;\n")
            fh.write("  function void run();\n")
            fh.write("    v = v + 1;\n")
            if i + 1 < N_CHAIN:
                fh.write("    if (nxt != null) nxt.run();\n")
            fh.write("  endfunction\n")
            fh.write("endclass\n")
        fh.write("module t (input clk);\n")
        fh.write("  C0 c = new;\n")
        fh.write("  always @(posedge clk) c.run();\n")
        fh.write("endmodule\n")


gen(test.top_filename)

# Statistics count the instructions of the evaluation functions along the chain, and V3Combine and
# thread scheduling hash the functions along it. Run with the default stack limit.
test.lint(threads=2, verilator_flags2=["--stats", "--no-unlimited-stack"])

test.passes()
