import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/" + test.name + ".v"

N = 500


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("interface bus_if #(parameter int W = 7);\n")
        fh.write("  logic [W-1:0] a;\nendinterface\n")
        fh.write("interface barrier_if #(parameter int TAG = 1);\n")
        fh.write("  logic [4:0] a;\nendinterface\n")
        fh.write("module sink (bus_if bus);\nendmodule\n")
        # Its own consumer module, as one also connected to a default interface instance fails
        # to connect, also on master
        fh.write("module stopped_sink (bus_if bus);\nendmodule\n")
        # Interface instances on paths sized by a large enum, its item or type, or a function
        fh.write("module holder;\n  typedef enum int {\n")
        fh.write(",\n".join("    E%d" % i for i in range(n)) + "\n  } e_t;\n")
        fh.write("  function automatic int f(input int a);\n    int r = a;\n")
        for i in range(n):
            fh.write("    r = r + %d;\n" % (i % 3))
        fh.write("    return r - %d;\n  endfunction\n" % sum(i % 3 for i in range(n)))
        for i in range(n):
            fh.write("  bus_if #(.W(E%d + %d)) b%d ();\n" % (n - 1, i % 7 + 1, i))
            fh.write("  bus_if #(.W($bits(e_t) + %d)) c%d ();\n" % (i % 7, i))
            fh.write("  bus_if #(.W(f(%d))) d%d ();\n" % (i % 7 + 1, i))
        fh.write("endmodule\n")
        # The same, each left to its turn by a later reference into an instance with
        # parameters, before the enum is sized
        fh.write("module stopped_holder;\n  typedef enum int {\n")
        fh.write(",\n".join("    S%d" % i for i in range(n)) + "\n  } s_t;\n")
        fh.write("  barrier_if #(.TAG(2)) slow ();\n")
        for i in range(n):
            fh.write("  bus_if #(.W(S%d + $bits(slow.a))) b%d ();\n" % (n - 1, i))
        fh.write("endmodule\n")
        # Instances on paths sized by a function of a parameterized module used with its defaults
        fh.write("module param_holder #(parameter int TAG = 1);\n")
        fh.write("  function automatic int f(input int a);\n    int r = a;\n")
        for i in range(n):
            fh.write("    r = r + 1;\n")
        fh.write("    return r - %d + TAG;\n  endfunction\n" % n)
        for i in range(n):
            fh.write("  bus_if #(.W(f(%d))) d%d ();\n" % (i % 7 + 1, i))
        fh.write("endmodule\n")
        # One instance on a path left to its turn, before the enum is sized, from each of many
        # modules visited in turn
        fh.write("module turn_holder;\n  typedef enum int {\n")
        fh.write(",\n".join("    U%d" % i for i in range(n)) + "\n  } u_t;\n")
        fh.write("  barrier_if #(.TAG(2)) slow ();\n")
        fh.write("  bus_if #(.W(U%d + $bits(slow.a))) b ();\nendmodule\n" % (n - 1))
        for i in range(n):
            fh.write("module turn_w%d;\n  stopped_sink s (.bus(h.b));\n  turn_holder h ();\n"
                     "endmodule\n" % i)
        # Paths through the instances of a module with many statements
        fh.write("module stmt_holder;\n  bus_if #(.W(9)) b ();\n")
        for i in range(n):
            fh.write("  logic s%d;\n" % i)
        fh.write("endmodule\n")
        fh.write("module t;\n")
        for i in range(n):
            fh.write("  sink sb%d (.bus(h.b%d));\n" % (i, i))
            fh.write("  sink sc%d (.bus(h.c%d));\n" % (i, i))
            fh.write("  sink sd%d (.bus(h.d%d));\n" % (i, i))
            fh.write("  stopped_sink ss%d (.bus(hs.b%d));\n" % (i, i))
        for i in range(n):
            fh.write("  sink sp%d (.bus(hp.d%d));\n" % (i, i))
            fh.write("  turn_w%d tw%d ();\n" % (i, i))
        fh.write("  holder h ();\n  stopped_holder hs ();\n  param_holder hp ();\n")
        for i in range(n // 10):
            fh.write("  sink st%d (.bus(ht%d.b));\n  stmt_holder ht%d ();\n" % (i, i, i))
        fh.write("endmodule\n")


gen(test.top_filename, N)

test.lint(verilator_flags2=['--stats'])

# Each item, enum item and statement is searched once, not once per instance or path, also
# when a search is left to its turn
test.file_grep(test.stats, r'Param, Template references searched\s+(\d+)', 20663)
test.file_grep(test.stats, r'Param, Defparam statements scanned\s+(\d+)', 4506)

test.passes()
