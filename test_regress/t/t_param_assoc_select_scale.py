import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/" + test.name + ".v"

# An associative array parameter, with each entry read once in a constant expression, by key kind:
# the key type declaration, the key of entry 'i', and the key read for genvar 'i'
KEY_KINDS = {
    'int': ("typedef int key_t;", lambda i: f"{i}", "i"),
    'struct': ("typedef struct {\n    int n;\n    bit tag;\n  } key_t;",
               lambda i: f"key_t'{{{i}, 1'b0}}", "key_t'{i, 1'b0}"),
    'real': ("typedef struct {\n    real r;\n    int n;\n  } key_t;",
             lambda i: f"key_t'{{{i}.5, {i}}}", "key_t'{i + 0.5, i}"),
    # Entries with a NaN, so matching no key read
    'nan': ("typedef struct {\n    real r;\n    int n;\n  } key_t;\n"
            "  localparam real NAN = $bitstoreal(64'h7ff8_0000_0000_0000);",
            lambda i: f"key_t'{{NAN, {i}}}", "key_t'{i + 0.5, i}"),
}
SIZE_RATIO = 4
SIZE_SMALL = 1000
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n, kind):
    typedef, entry_key, read_key = KEY_KINDS[kind]
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write(f"module t (output wire [{n - 1}:0] y);\n")
        fh.write(f"  {typedef}\n")
        fh.write("  localparam bit LUT[key_t] = '{\n")
        fh.write(",\n".join(f"      {entry_key(i)}: 1'b{i % 2}" for i in range(n)))
        fh.write("\n  };\n")
        fh.write(f"  for (genvar i = 0; i < {n}; ++i) begin : g\n")
        fh.write(f"    localparam bit V = LUT[{read_key}];\n")
        fh.write("    assign y[i] = V;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def verilation(n, kind):
    gen(test.top_filename, n, kind)
    test.compile(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    return test.op_count_read(test.stats)


for key_kind in KEY_KINDS:
    test.op_count_ok(verilation(SIZE_SMALL, key_kind), verilation(SIZE_LARGE, key_kind), RATIO_MIN,
                     RATIO_MAX, r'.*')

test.passes()
