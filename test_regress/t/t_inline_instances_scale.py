import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_inline_instances_scale.v"

# Many instances of one small module under a single parent instance. V3Inline inlines each of
# them, and their parent into the top. The model is not built.
N_INSTANCES = 8000
# Share of verilation time spent in V3Inline (about 0.04 when linear, 0.45 when quadratic)
MAX_SHARE = 0.2
# Ignore a high share of a short time, e.g. from a load spike (quadratic takes about 2 s)
MIN_SECONDS = 0.5


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"""// Generated by t_inline_instances_scale.py
module leaf (input clk, input d, output logic q);
  always_ff @(posedge clk) q <= d;
endmodule
module mid (input clk, input [{N_INSTANCES - 1}:0] d, output [{N_INSTANCES - 1}:0] q);
  for (genvar i = 0; i < {N_INSTANCES}; ++i) begin : g
    leaf u_leaf (.clk(clk), .d(d[i]), .q(q[i]));
  end
endmodule
module t (input clk, input [{N_INSTANCES - 1}:0] d, output [{N_INSTANCES - 1}:0] q);
  mid u_mid (.clk(clk), .d(d), .q(q));
endmodule
""")


gen(test.top_filename)

test.compile(verilator_flags2=["--stats", "--no-debug-check"],
             make_main=False,
             verilator_make_gmake=False)

# The leaf instances, the mid instance, and the top module instance under $root
test.file_grep(test.stats, r'Optimizations, Inlined instances\s+(\d+)', N_INSTANCES + 2)
stats = test.file_contents(test.stats)
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
inline = re.search(r'Stage, Elapsed time \(sec\), \d+_inline\s+(\S+)', stats)
if not total or not inline:
    test.error("Stage elapsed times not found in " + test.stats)
seconds = float(inline.group(1))
share = seconds / float(total.group(1))
if seconds > MIN_SECONDS and share > MAX_SHARE:
    test.error(f"V3Inline took {share:.0%} of verilation time with {N_INSTANCES} instances " +
               f"(over {MAX_SHARE:.0%})")

test.passes()
