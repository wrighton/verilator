import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_constraint_nested_static_scale.v"

# Many classes constraining a static rand member of a class, each with a rand handle of a
# class with many derived classes; and each extending a class with many rand handles
SIZE_SMALL = 100
SIZE_LARGE = 400
RATIO_MIN = 3
RATIO_MAX = 6  # Linear scaling gives 4x, quadratic gives 16x


def gen_family(fh, n):
    fh.write("class Fam;\n  rand bit [7:0] f;\nendclass\n")
    for i in range(n):
        fh.write(f"class F{i} extends Fam;\nendclass\n")
        fh.write(f"class K{i};\n  rand bit [7:0] k;\n  rand Fam fm;\n")
        fh.write("  constraint c {k == Cfg::s;}\nendclass\n")


def gen_inherited(fh, n):
    fh.write("class Fld;\n  rand bit [7:0] f;\nendclass\n")
    fh.write("class Base;\n")
    for i in range(n):
        fh.write(f"  rand Fld f{i};\n")
    fh.write("endclass\n")
    for i in range(n):
        fh.write(f"class K{i} extends Base;\n  rand bit [7:0] k;\n")
        fh.write("  constraint c {k == Cfg::s;}\nendclass\n")


def gen_chain(fh, n):
    fh.write("class L0;\n  rand bit [7:0] f;\nendclass\n")
    for i in range(1, n):
        fh.write(f"class L{i} extends L{i - 1};\nendclass\n")
    for i in range(n):
        fh.write(f"class K{i};\n  rand bit [7:0] k;\n  rand L{i} h;\n")
        fh.write("  constraint c {k == Cfg::s;}\nendclass\n")


def verilation(gen, n):
    with open(test.top_filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_constraint_nested_static_scale.py\n")
        fh.write("class Cfg;\n  static rand bit [7:0] s;\nendclass\n")
        gen(fh, n)
        fh.write("module t;\n  initial begin\n")
        for i in range(n):
            fh.write(f"    automatic K{i} k{i} = new;\n")
        for i in range(n):
            fh.write(f"    void'(k{i}.randomize());\n")
        fh.write("  end\nendmodule\n")
    test.compile(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    test.file_cache_clear()
    return test.op_count_read(test.stats)


def check_steps(exp):
    test.file_grep(test.stats, r'Randomize, static rand member reachability steps\s+(\d+)', exp)


# Each class's own members are scanned once per owner: linearly
small = verilation(gen_family, SIZE_SMALL)
large = verilation(gen_family, SIZE_LARGE)
test.op_count_ok(small, large, RATIO_MIN, RATIO_MAX, r'randomize')
check_steps(7 * SIZE_LARGE + 3)
# The randomize() of each class handles the members it inherits, so only the steps are linear
verilation(gen_inherited, SIZE_SMALL)
check_steps(5 * SIZE_SMALL + 4)
# Each class of a chain of derived classes is checked once for extending the members' class
verilation(gen_chain, SIZE_SMALL)
check_steps(9 * SIZE_SMALL - 1)

test.passes()
