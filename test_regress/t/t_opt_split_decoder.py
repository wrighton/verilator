import vltest_bootstrap

test.scenarios('simulator')
test.top_filename = test.obj_dir + "/t_opt_split_decoder.v"
test.sim_time = 2500

# Registers written by a case statement. V3Case makes it an if/else chain, and splitting would
# copy the chain above each register for each register, so this block is not split.
NBIG = 96
# A few registers, splitting copies little, so this block is split.
NSMALL = 4


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_opt_split_decoder.py\n")
        fh.write("`define checkh(gotv,expv) do if ((gotv) !== (expv)) begin " +
                 "$write(\"%%Error: %s:%0d:  got='h%x exp='h%x\\n\", " +
                 "`__FILE__,`__LINE__, (gotv), (expv)); $stop; end while(0);\n")
        fh.write("module t (\n")
        fh.write("    input clk\n")
        fh.write(");\n")
        fh.write("  int cyc = 0;\n")
        fh.write(f"  wire we = cyc < {NBIG};\n")
        fh.write(f"  wire [31:0] addr = we ? cyc : cyc - {NBIG};\n")
        fh.write("  wire [31:0] wdata = (addr + 1) * 32'h9e3779b9;\n")
        for name, n, value in (("r", NBIG, "wdata"), ("s", NSMALL, "~wdata")):
            for i in range(n):
                fh.write(f"  logic [31:0] {name}{i};\n")
            fh.write("  always_ff @(posedge clk) begin\n")
            fh.write("    if (we) begin\n")
            fh.write("      case (addr)\n")
            for i in range(n):
                fh.write(f"        {i}: {name}{i} <= {value};\n")
            fh.write("        default: ;\n")
            fh.write("      endcase\n")
            fh.write("    end\n")
            fh.write("  end\n")
            fh.write(f"  logic [31:0] {name}data;\n")
            fh.write("  always_comb begin\n")
            fh.write("    case (addr)\n")
            for i in range(n):
                fh.write(f"      {i}: {name}data = {name}{i};\n")
            fh.write(f"      default: {name}data = 0;\n")
            fh.write("    endcase\n")
            fh.write("  end\n")
        fh.write("  always @(posedge clk) begin\n")
        fh.write("    cyc <= cyc + 1;\n")
        fh.write("    if (!we) begin\n")
        fh.write("      // Registers written in the first half are read back in the second\n")
        fh.write("      `checkh(rdata, wdata);\n")
        fh.write(f"      if (addr < {NSMALL}) `checkh(sdata, ~wdata);\n")
        fh.write("    end\n")
        fh.write(f"    if (cyc == {2 * NBIG - 1}) begin\n")
        fh.write("      $write(\"*-* All Finished *-*\\n\");\n")
        fh.write("      $finish;\n")
        fh.write("    end\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

# The block that is not split cannot be spread over threads
test.compile(verilator_flags2=["--stats", "-Wno-UNOPTTHREADS"])

if test.vlt_all:
    # The small decoder, and the checking block
    test.file_grep(test.stats, r'Optimizations, Split always\s+(\d+)', (NSMALL - 1) + 1)
    test.file_grep(test.stats, r'Optimizations, Split always declined as too large\s+(\d+)', 1)

test.execute()

test.passes()
