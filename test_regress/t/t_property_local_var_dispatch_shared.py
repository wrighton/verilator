import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_property_local_var_dispatch_shared.v"

# Match item values each calling a virtual method on an object of a different interface class,
# all of which a balanced tree of interface classes joins above one implementing class with
# N_RECEIVERS subclasses, so the calls share their possible targets
N_RECEIVERS = 512
# Match item values each calling a different virtual method of one class with N_NAMES subclasses
# defining none of them
N_NAMES = 256
# A match item value calling a virtual method of a class calling a virtual method of the same
# name of another class, and so on through N_DELEGATES classes
N_DELEGATES = 2048
# The work of lowering the values, linear if each target is classified once
MAX_WORK = 100 * N_RECEIVERS + 100 * N_NAMES + 20 * N_DELEGATES


def gen(filename):
    proto = "pure virtual function int value(int n);"
    impl = "virtual function int value(int n); return n + 1; endfunction"
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_property_local_var_dispatch_shared.py\n")
        for i in range(N_RECEIVERS):
            fh.write(f"interface class I{i}; {proto} endclass\n")
        level = [f"I{i}" for i in range(N_RECEIVERS)]
        k = 0
        while len(level) > 1:
            next_level = []
            for i in range(0, len(level) - 1, 2):
                fh.write(f"interface class J{k} extends {level[i]}, {level[i + 1]}; {proto}" +
                         " endclass\n")
                next_level.append(f"J{k}")
                k += 1
            if len(level) % 2:
                next_level.append(level[-1])
            level = next_level
        fh.write(f"class D implements {level[0]}; {impl} endclass\n")
        for i in range(N_RECEIVERS):
            fh.write(f"class L{i} extends D; {impl} endclass\n")
        fh.write("class B;\n")
        for i in range(N_NAMES):
            fh.write(f"  virtual function int value{i}(int n); return n + {i}; endfunction\n")
        fh.write("endclass\n")
        for i in range(N_NAMES):
            fh.write(f"class E{i} extends B; endclass\n")
        fh.write("class G0;" +
                 " virtual function int forward(int n); return n + 1; endfunction endclass\n")
        for i in range(1, N_DELEGATES):
            fh.write(f"class G{i}; G{i - 1} next; virtual function int forward(int n);" +
                     " return next.forward(n); endfunction endclass\n")
        fh.write("module t (input clk, input int n);\n")
        fh.write(f"  G{N_DELEGATES - 1} g;\n")
        fh.write("  function automatic int delegate(int x); return g.forward(x); endfunction\n")
        fh.write("  property q; int v; @(posedge clk) (1, v = delegate(n)) ##0 (v == n + 1);" +
                 " endproperty\n")
        fh.write("  assert property (q);\n")
        fh.write("  B nb = new;\n")
        for i in range(N_NAMES):
            fh.write(
                f"  function automatic int name{i}(int x); return nb.value{i}(x); endfunction\n")
            fh.write(f"  property q{i}; int v; @(posedge clk) (1, v = name{i}(n))" +
                     f" |=> (v == $past(n) + {i}); endproperty\n")
            fh.write(f"  assert property (q{i});\n")
        for i in range(N_RECEIVERS):
            fh.write(f"  I{i} b{i};\n")
            fh.write(
                f"  function automatic int calc{i}(int x); return b{i}.value(x); endfunction\n")
            fh.write(f"  property p{i}; int v; @(posedge clk) (1, v = calc{i}(n))" +
                     " |=> (v == $past(n) + 1); endproperty\n")
            fh.write(f"  assert property (p{i});\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--assert", "--timing"])

work = re.search(r'Assertions, local variable lowering work\s+(\d+)',
                 test.file_contents(test.stats))
if not work:
    test.error("Lowering work not found in " + test.stats)
if int(work.group(1)) > MAX_WORK:
    test.error(f"Lowering work {work.group(1)} with {N_RECEIVERS} receivers, {N_NAMES}" +
               f" method names and {N_DELEGATES} delegates (over {MAX_WORK})")

test.passes()
