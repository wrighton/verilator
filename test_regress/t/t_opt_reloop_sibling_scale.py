import vltest_bootstrap

test.scenarios('vlt')

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# Nested 'if's, each followed by a short 'if' of the same type, so V3Reloop sees deeply nested
# statements with same-type siblings that cannot form a run. Only measures V3Reloop operations,
# the model is not built.
SIZE_RATIO = 4
SIZE_SMALL = 100
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 1
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("module t (input clk, input int sel, input int a, output int q[8]);\n")
        fh.write("  always_ff @(posedge clk) begin\n")
        for i in range(n):
            fh.write(f"    if (sel == {i * 7}) begin\n")
            fh.write(f"      q[{i % 8}] <= a + {i};\n")
            fh.write(f"      q[{(i + 3) % 8}] <= a - {i};\n")
            fh.write("    end else begin\n")
        fh.write("    q[7] <= a;\n")
        for i in reversed(range(n)):
            fh.write(f"    if (a == {i * 9 + 1}) q[{(i + 4) % 8}] <= sel ^ {i};\n")
            fh.write("    end\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    # Disable other passes that are slow on this code, to keep the test fast
    test.compile(verilator_flags2=[
        "--stats", "--debug", "--debugi 0", "--no-debug-check", "-fno-dfg", "-fno-merge-cond",
        "-fno-split"
    ],
                 make_main=False,
                 verilator_make_gmake=False)
    return test.op_count_read(test.stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX, r'reloop')

test.passes()
