import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_property_local_var_dispatch_scale.v"

# Interface classes L{i}a and L{i}b each extend both L{i-1}a and L{i-1}b, so the number of
# inheritance paths from the implementing class is exponential in the depth
N_LEVELS = 30
# Classes C{i} each extend C{i-1}, overriding a virtual method r calling virtual method q, so the
# calls of q have as many receiver classes as there are levels
N_CHAIN = 1000
# Classes O{i} each extend O{i-1}, overriding a virtual method calling the method of the same
# name on an object of an unrelated class
N_OVERRIDES = 1000
# The work of lowering values calling the virtual methods, linear in the levels
MAX_WORK = 100 * N_LEVELS + 50 * N_CHAIN + 50 * N_OVERRIDES
# Time of the NFA lowering, a fraction of a second if linear, many seconds if exponential
MAX_SECONDS = 2.0


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_property_local_var_dispatch_scale.py\n")
        for x in "ab":
            fh.write(f"interface class L0{x};\n")
            fh.write("  pure virtual function int unsigned r();\n")
            fh.write("endclass\n")
        for i in range(1, N_LEVELS):
            for x in "ab":
                fh.write(f"interface class L{i}{x} extends L{i - 1}a, L{i - 1}b;\n")
                fh.write("  pure virtual function int unsigned r();\n")
                fh.write("endclass\n")
        fh.write(f"class Imp implements L{N_LEVELS - 1}a;\n")
        fh.write("  virtual function int unsigned r();\n")
        fh.write("    return 42;\n")
        fh.write("  endfunction\n")
        fh.write("endclass\n")
        fh.write("class B;\n")
        fh.write("  virtual function int unsigned r();\n")
        fh.write("    return 42;\n")
        fh.write("  endfunction\n")
        fh.write("endclass\n")
        fh.write("class C0;\n")
        fh.write("  virtual function int r();\n")
        fh.write("    return q();\n")
        fh.write("  endfunction\n")
        fh.write("  virtual function int q();\n")
        fh.write("    return 0;\n")
        fh.write("  endfunction\n")
        fh.write("endclass\n")
        for i in range(1, N_CHAIN):
            fh.write(f"class C{i} extends C{i - 1};\n")
            fh.write("  virtual function int r();\n")
            fh.write("    return q();\n")
            fh.write("  endfunction\n")
            fh.write("  virtual function int q();\n")
            fh.write(f"    return {i};\n")
            fh.write("  endfunction\n")
            fh.write("endclass\n")
        fh.write("class S0;\n")
        fh.write("  virtual function int s();\n")
        fh.write("    return 42;\n")
        fh.write("  endfunction\n")
        fh.write("endclass\n")
        fh.write("class O0;\n")
        fh.write("  S0 delegate = new;\n")
        fh.write("  virtual function int s();\n")
        fh.write("    return delegate.s();\n")
        fh.write("  endfunction\n")
        fh.write("endclass\n")
        for i in range(1, N_OVERRIDES):
            fh.write(f"class O{i} extends O{i - 1};\n")
            fh.write("  virtual function int s();\n")
            fh.write("    return delegate.s();\n")
            fh.write("  endfunction\n")
            fh.write("endclass\n")
        fh.write("module t (input clk);\n")
        fh.write("  O0 o0 = new;\n")
        fh.write("  B b0 = new;\n")
        fh.write("  L0a l0 = null;\n")
        fh.write("  C0 c0 = new;\n")
        # Two values making the same call, the receiver of a diamond, and the chains
        for name, call in (("g", "b0.r()"), ("g2", "b0.r()"), ("gl", "l0.r()"), ("gc", "c0.r()"),
                           ("go", "o0.s()")):
            fh.write(f"  function automatic int unsigned {name}();\n")
            fh.write(f"    return {call};\n")
            fh.write("  endfunction\n")
            fh.write(f"  property p_{name};\n")
            fh.write("    int unsigned v;\n")
            fh.write(f"    @(posedge clk) (1, v = {name}()) |=> (v != 1);\n")
            fh.write("  endproperty\n")
            fh.write(f"  assert property (p_{name});\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--assert", "--timing"])

stats = test.file_contents(test.stats)
work = re.search(r'Assertions, local variable lowering work\s+(\d+)', stats)
nfa = re.search(r'Stage, Elapsed time \(sec\), \d+_assertnfa\s+(\S+)', stats)
if not work or not nfa:
    test.error("Lowering work or time not found in " + test.stats)
if float(nfa.group(1)) > MAX_SECONDS:
    test.error(f"NFA lowering took {nfa.group(1)} s with {N_LEVELS} interface class levels," +
               f" {N_CHAIN} and {N_OVERRIDES} class levels")
if int(work.group(1)) > MAX_WORK:
    test.error(f"Lowering work {work.group(1)} with {N_LEVELS} interface class levels," +
               f" {N_CHAIN} and {N_OVERRIDES} class levels (over {MAX_WORK})")

test.passes()
