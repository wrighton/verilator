import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_lint_multidriven_call_scale.v"

# Each method writes its member and calls the next one, so each reaches all methods after it in
# a chain of N_CHAIN methods
N_CHAIN = 3000
# Memory growth in V3Undriven, as a share of the memory used before (about 0.001 when linear,
# 0.2 when each method stores all variables it reaches)
MAX_GROWTH = 0.1
# Share of verilation time spent in V3Undriven (about 0.03 when linear, 0.6 when each method
# stores all variables it reaches)
MAX_SHARE = 0.2
# Ignore a high share of a short time, e.g. from a load spike
MIN_SECONDS = 0.5


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_lint_multidriven_call_scale.py\n")
        for i in reversed(range(N_CHAIN)):
            fh.write(f"class C{i};\n")
            fh.write("  int v;\n")
            if i + 1 < N_CHAIN:
                fh.write(f"  C{i + 1} nxt;\n")
            fh.write("  function void run();\n")
            fh.write("    v = v + 1;\n")
            if i + 1 < N_CHAIN:
                fh.write("    if (nxt != null) nxt.run();\n")
            fh.write("  endfunction\n")
            fh.write("endclass\n")
        fh.write("module t;\n")
        fh.write("  initial begin\n")
        fh.write("    automatic C0 c = new;\n")
        fh.write("    c.run();\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--no-debug-check"])

with open(test.stats, 'r', encoding="utf8") as fh:
    stats = fh.read()
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
undriven = re.search(r'Stage, Elapsed time \(sec\), \d+_undriven\s+(\S+)', stats)
memories = re.findall(r'Stage, Memory current \(MB\), \d+_(\S+)\s+(\S+)', stats)
names = [name for name, _ in memories]
if not total or not undriven or 'undriven' not in names:
    test.error("Stage statistics not found in " + test.stats)

seconds = float(undriven.group(1))
share = seconds / float(total.group(1))
if seconds > MIN_SECONDS and share > MAX_SHARE:
    test.error(f"V3Undriven took {share:.0%} of verilation time (over {MAX_SHARE:.0%})")

# Memory statistics are zero where the OS does not report them
i = names.index('undriven')
before = float(memories[i - 1][1])
growth = (float(memories[i][1]) - before) / before if before else 0
if growth > MAX_GROWTH:
    test.error(f"Memory grew by {growth:.0%} in V3Undriven (over {MAX_GROWTH:.0%})")

test.passes()
