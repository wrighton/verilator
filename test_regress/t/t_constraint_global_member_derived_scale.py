# The constraints of K member classes, each reaching a class derived from the randomized
# class, are cloned once each: 3 clones for each K, not more as clones are cloned again

import os
import re
import vltest_bootstrap

test.scenarios('vlt')
test.timeout(300 if not test.have_dev_asan else 900)


def gen(filename, k):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_constraint_global_member_derived_scale.py\n")
        for i in range(k):
            fh.write(f"typedef class M{i};\n")
            fh.write(f"typedef class D{i};\n")
        fh.write("class A;\n  rand int x;\n")
        for i in range(k):
            fh.write(f"  rand M{i} m{i};\n")
        fh.write("  constraint c_a {x inside {[1 : 9]};}\nendclass\n")
        for i in range(k):
            fh.write(f"class D{i} extends A;\n  rand int z;\n")
            fh.write(f"  constraint c_d {{z == x + {i};}}\nendclass\n")
            fh.write(f"class M{i};\n  rand int y;\n  rand D{i} d;\n")
            fh.write(f"  constraint c_m {{y > {i};}}\nendclass\n")
        fh.write("module t;\n  initial begin\n    automatic A a = new;\n")
        fh.write("    automatic int ok;\n    ok = a.randomize();\n    $finish;\n")
        fh.write("  end\nendmodule\n")


def code(k):
    filename = test.obj_dir + "/scale" + str(k) + ".v"
    mdir = test.obj_dir + "/scale" + str(k)
    gen(filename, k)
    test.run(cmd=[
        "perl", os.environ["VERILATOR_ROOT"] + "/bin/verilator", "--cc", "-Wno-fatal", "--Mdir",
        mdir, filename
    ],
             logfile=mdir + ".log",
             verilator_run=True)
    text = ""
    for f in sorted(os.listdir(mdir)):
        if f.endswith(".cpp") or f.endswith(".h"):
            with open(os.path.join(mdir, f), 'r', encoding="utf8") as fh:
                text += fh.read()
    return text


sizes = {}
for k in (2, 4, 8, 16):
    text = code(k)
    sizes[k] = len(text)
    # A clone's setup is named by its path from the randomized class
    clones = set(re.findall(r'\w*__DT__\w*_setup_constraint', text))
    if len(clones) != 3 * k:
        test.error("K=" + str(k) + ": " + str(len(clones)) + " cloned constraints, expected " +
                   str(3 * k))
# The classes' own code grows with K squared, as each D inherits K handles
for k in (4, 8, 16):
    if sizes[k] > 4 * sizes[k // 2]:
        test.error("Code size grows faster than K squared: " + str(sizes))
if sizes[16] > 2000000:
    test.error("Code size over 2 MB at K=16: " + str(sizes))

test.passes()
