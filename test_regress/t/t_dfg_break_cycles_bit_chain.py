import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# A vector driven bit by bit from its own lower bits. Breaking the cycle should take work linear
# in the width.
SIZE_RATIO = 4
SIZE_SMALL = 250
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x
# Vertices visited when tracing the drivers of the independent bits, also linear in the width
VERTICES_TRACED = {SIZE_SMALL: 1739, SIZE_LARGE: 6989}


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"""// Generated by {test.name}.py
module t (input logic [63:0] i, output logic [63:0] o);
  logic [{n - 1}:0] v;
  assign v[0] = i[0];
  for (genvar k = 1; k < {n}; ++k) begin : g
    assign v[k] = v[k - 1] ^ i[k % 64];
  end
  assign o = v[{n - 1}:{n - 64}];
endmodule
""")


def verilation(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    test.file_cache_clear()
    test.file_grep(test.stats, r'Optimizations, DFG, BreakCycles, made acyclic\s+(\d+)', 1)
    test.file_grep(test.stats, r'Optimizations, DFG, BreakCycles, vertices traced\s+(\d+)',
                   VERTICES_TRACED[n])
    return test.op_count_read(test.stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX,
                 r'dfg-breakCycles')

test.passes()
