import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_lint_eofnewline_bad.v"


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_lint_eofnewline_bad.py\n")
        fh.write("module t;\n")
        fh.write("  sub sub ();\n")
        fh.write("// No newline below:\n")
        fh.write("endmodule")
        # Intentionally no newline


def gen_sub(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        # The preprocessor warning is on line 1, where parsing first applies ignores.
        fh.write("/*verilator_bad*/ module sub; endmodule\n")


sub_filename = test.obj_dir + "/t_lint_eofnewline_sub.v"
gen(test.top_filename)
gen_sub(sub_filename)

test.lint(verilator_flags2=["-Wall", test.vlt_filename, sub_filename])

test.passes()
