import re

import vltest_bootstrap

test.scenarios('vlt')

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# Each module is emitted to its own files, all with about the same score. The 240 slow files
# are grouped, about 4.8 per output group. Filling each group with the number of files closest
# to one fixed ideal score gives 4 files per group, and the files left over used to all go into
# the last group.
MODULES = 120
GROUPS = 50


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"// Generated by {test.name}.py\n")
        for i in range(MODULES):
            fh.write(f"""module m{i} (input clk, input [31:0] d, output logic [31:0] q);
  /*verilator no_inline_module*/
  always_ff @(posedge clk) q <= d + 32'd{i};
endmodule
""")
        fh.write(f"""module t (input clk, input [31:0] d, output logic [31:0] q);
  logic [31:0] w[{MODULES}];
""")
        for i in range(MODULES):
            fh.write(f"  m{i} u{i} (.clk(clk), .d(d), .q(w[{i}]));\n")
        fh.write(f"""  always_comb begin
    q = 0;
    for (int i = 0; i < {MODULES}; ++i) q ^= w[i];
  end
endmodule
""")


gen(test.top_filename)

test.compile(verilator_flags2=["--output-groups", str(GROUPS)],
             make_main=False,
             verilator_make_gmake=False)

# Every group of slow files holds about the same number of files
counts = {}
for filename in test.glob_some(test.obj_dir + "/" + test.vm_prefix + "_vm_classes_Slow_*.cpp"):
    with open(filename, 'r', encoding="utf8") as fh:
        counts[filename] = len(re.findall(r'^#include', fh.read(), re.MULTILINE))
if len(counts) != GROUPS:
    test.error(f"Found {len(counts)} groups of slow files, expected {GROUPS}")
average = sum(counts.values()) / len(counts)
for filename, count in sorted(counts.items()):
    if count > 2 * average:
        test.error(f"{filename} includes {count} files, the average group {average:.1f}")

test.passes()
