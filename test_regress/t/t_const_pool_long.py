import vltest_bootstrap

test.scenarios('simulator')
test.top_filename = test.obj_dir + "/t_const_pool_long.v"

# Containers with more items than one C++ initializer takes
N = 1000


def items(fmt):
    # 'w' has no zero bytes, as a wildcard key
    return ",\n    ".join(fmt % {
        'i': i,
        'k': 2 * i,
        'v': (i * 7) % 1009,
        'w': ((i // 255 + 1) << 8) | (i % 255 + 1)
    } for i in range(N))


with open(test.top_filename, 'w', encoding="utf8") as fh:
    fh.write("// Generated by t_const_pool_long.py\n")
    fh.write("`define stop $stop\n")
    fh.write("module t;\n")
    # In the constant pool
    fh.write("  int q[$] = '{\n    " + items("%(v)d") + "};\n")
    fh.write("  int d[] = '{\n    " + items("%(v)d") + "};\n")
    fh.write("  int kq[$] = '{\n    " + items("%(k)d: %(v)d") + ", default: -1};\n")
    fh.write("  string kd[] = '{\n    " + items('%(i)d: "s%(v)d"') + "};\n")
    fh.write("  int aa[int] = '{\n    " + items("%(v)d: %(i)d") + ", default: -1};\n")
    fh.write("  int wa[*] = '{\n    " + items("16'd%(w)d: %(v)d") + ", default: -1};\n")
    fh.write("  int qq[$][$] = '{'{\n    " + items("%(v)d") + "}};\n")
    # Not in the constant pool, as bounded
    fh.write("  int bq[$:%d] = '{\n    " % N + items("%(v)d") + "};\n")
    fh.write("""  initial begin
    if (q.size() != %(n)d || d.size() != %(n)d || kq.size() != 2 * %(n)d - 1) `stop;
    if (kd.size() != %(n)d || qq.size() != 1 || qq[0].size() != %(n)d || bq.size() != %(n)d)
      `stop;
    if (aa.num() != %(n)d || wa.num() != %(n)d || aa[1009] != -1 || wa[0] != -1) `stop;
    for (int i = 0; i < %(n)d; ++i) begin
      automatic int v = (i * 7) %% 1009;
      if (q[i] != v || d[i] != v || qq[0][i] != v || bq[i] != v) `stop;
      if (kq[2 * i] != v || (i > 0 && kq[2 * i - 1] != -1)) `stop;
      if (kd[i] != $sformatf("s%%0d", v)) `stop;
      if (aa[v] != i || wa[{8'(i / 255 + 1), 8'(i %% 255 + 1)}] != v) `stop;
    end
    $write("*-* All Finished *-*\\n");
    $finish;
  end
endmodule
""" % {'n': N})

test.compile(verilator_flags2=["--stats"])

test.execute()

test.file_grep(test.stats, r'ConstPool, CONSASSOC emitted\s+(\d+)', 1)
test.file_grep(test.stats, r'ConstPool, CONSDYNARRAY emitted\s+(\d+)', 2)
test.file_grep(test.stats, r'ConstPool, CONSQUEUE emitted\s+(\d+)', 3)
test.file_grep(test.stats, r'ConstPool, CONSWILDCARD emitted\s+(\d+)', 1)

test.passes()
