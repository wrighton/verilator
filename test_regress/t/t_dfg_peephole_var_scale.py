import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_dfg_peephole_var_scale.v"

# Variables d<i> all copying the same signal, each read by the same expression. DFG CSE merges
# the expressions, so the signal is left with one real sink and N_VARS removable variables,
# which DFG peephole removes. The model is not built.
N_VARS = 10000
# Share of verilation time spent in DFG peephole (about 0.01 when linear, 0.5 when quadratic)
MAX_SHARE = 0.2
# Ignore a high share of a short time, e.g. from a load spike (quadratic takes about 1.2 s,
# linear about 0.01 s)
MIN_SECONDS = 0.1


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_dfg_peephole_var_scale.py\n")
        fh.write(f"module t (input [7:0] a, input [7:0] b, output [{8 * N_VARS - 1}:0] q);\n")
        fh.write("  wire [7:0] s = a & b;\n")
        fh.write(f"  for (genvar i = 0; i < {N_VARS}; ++i) begin : g\n")
        fh.write("    wire [7:0] d = s;\n")
        fh.write("    assign q[i * 8 +: 8] = d & 8'h0f;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.compile(verilator_flags2=["--stats", "--no-debug-check"],
             make_main=False,
             verilator_make_gmake=False)

test.file_grep(test.stats, r'Optimizations, DFG, Peephole, remove var\s+(\d+)', N_VARS + 1)
stats = test.file_contents(test.stats)
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
peephole = re.findall(r'Stage, Elapsed time \(sec\), \d+_dfg-peephole\s+(\S+)', stats)
if not total or not peephole:
    test.error("Stage elapsed times not found in " + test.stats)
seconds = sum(float(t) for t in peephole)
share = seconds / float(total.group(1))
if seconds > MIN_SECONDS and share > MAX_SHARE:
    test.error(f"DFG peephole took {share:.0%} of verilation time with {N_VARS} variables " +
               f"(over {MAX_SHARE:.0%})")

test.passes()
