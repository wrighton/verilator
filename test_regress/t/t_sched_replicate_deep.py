import os
import re

import vltest_bootstrap

test.scenarios('vlt')

# Sanitizer and debug compiler stack frames are larger, so other passes recursing along the chain
# (V3Gate unused logic marking, V3Graph strongly connected components) overflow
if (test.have_dev_asan or test.tsan
        or re.search(r'--debug(\s|$)', ' '.join(test.driver_verilator_flags))
        or os.environ.get('VERILATOR_BIN', '').endswith('_dbg')):
    test.skip("Too deep with sanitizers or the debug compiler")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# A chain of combinational assignments, each reading the two before it, driven
# by both a register and an input, longer than recursion along it can go on the
# default stack
N = 45000

with open(test.top_filename, 'w', encoding="utf8") as fh:
    fh.write("// Generated by " + test.name + ".py\n")
    fh.write("module t (input logic clk, input logic [63:0] i, output logic [63:0] o);\n")
    fh.write("  logic [63:0] r;\n")
    fh.write("  always_ff @(posedge clk) r <= i ^ o;\n")
    for n in range(N):
        fh.write("  logic [63:0] w%d;\n" % n)
    fh.write("  assign w0 = r;\n")
    fh.write("  assign w1 = r ^ i;\n")
    for n in range(2, N):
        fh.write("  assign w%d = (w%d << 1) ^ (w%d >> 3) ^ i;\n" % (n, n - 1, n - 2))
    fh.write("  assign o = w%d;\n" % (N - 1))
    fh.write("endmodule\n")

# Run with the default stack limit, and only verilate, as the C++ is large.
# Without DFG, as its walks along the chain are covered by t_dfg_deep_path.
test.compile(verilator_flags2=['--no-unlimited-stack', '-fno-dfg'], verilator_make_gmake=False)

test.passes()
