import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_inst_missing_pin_scale.v"

# N instances of a module with N ports, each connecting only one, so each is missing N - 1
N = 200


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_inst_missing_pin_scale.py\n")
        fh.write("module sub (\n")
        fh.write(",\n".join(f"    input logic i{k}" for k in range(n)))
        fh.write("\n);\nendmodule\n")
        fh.write("module t (\n    input logic i\n);\n")
        for k in range(n):
            fh.write(f"  sub u{k} (.i{k}(i));\n")
        fh.write("endmodule\n")


gen(test.top_filename, N)

test.lint(verilator_flags2=["--stats", "-Wno-PINMISSING"])

# The statements of sub, N ports and N variables, are searched for the variables of missing
# pins once, not for each missing pin of each instance
test.file_grep(test.stats, r'LinkCells, Module statements scanned for variables\s+(\d+)', 2 * N)

test.passes()
