import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_timing_suspendable_scale.v"

# Every class overrides a virtual task calling one shared function, so the shared function
# and the base task each have N_CLASSES dependents in the timing dependency graphs
N_CLASSES = 2000
# Interface classes Dag2..Dag{N_DAG} each extend the previous two without redeclaring the
# method, so the number of inheritance paths from the implementing class to Dag0 is exponential
N_DAG = 30
# Share of verilation time spent in V3Timing (about 0.02 when linear, 0.45 when quadratic in
# N_CLASSES, 0.6 when exponential in N_DAG)
MAX_SHARE = 0.15


def gen(filename, n, n_dag):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_timing_suspendable_scale.py\n")
        fh.write("class Base;\n")
        fh.write("  static int cnt;\n")
        fh.write("  static function void log(int i);\n")
        fh.write("    cnt += i;\n")
        fh.write("  endfunction\n")
        fh.write("  virtual task body();\n")
        fh.write("  endtask\n")
        fh.write("endclass\n")
        for i in range(n):
            fh.write(f"class C{i} extends Base;\n")
            fh.write("  virtual task body();\n")
            fh.write(f"    log({i});\n")
            fh.write("    #1;\n")
            fh.write("  endtask\n")
            fh.write("endclass\n")
        fh.write("interface class Dag0;\n")
        fh.write("  pure virtual task body();\n")
        fh.write("endclass\n")
        fh.write("interface class Dag1 extends Dag0;\n")
        fh.write("endclass\n")
        for i in range(2, n_dag + 1):
            fh.write(f"interface class Dag{i} extends Dag{i - 1}, Dag{i - 2};\n")
            fh.write("endclass\n")
        fh.write(f"class DagImpl implements Dag{n_dag};\n")
        fh.write("  virtual task body();\n")
        fh.write("    #1;\n")
        fh.write("  endtask\n")
        fh.write("endclass\n")
        fh.write("module t;\n")
        fh.write("  initial begin\n")
        fh.write("    Base b;\n")
        fh.write("    Dag0 d;\n")
        for i in range(0, n, n // 8):
            fh.write(f"    begin automatic C{i} c = new; b = c; b.body(); end\n")
        fh.write("    begin automatic DagImpl c = new; d = c; d.body(); end\n")
        fh.write("    $finish;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename, N_CLASSES, N_DAG)

test.compile(verilator_flags2=["--timing", "--stats", "--no-debug-check"],
             make_main=False,
             verilator_make_gmake=False)

with open(test.stats, 'r', encoding="utf8") as fh:
    stats = fh.read()
timing = re.search(r'Stage, Elapsed time \(sec\), \d+_timing\s+(\S+)', stats)
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
if not timing or not total:
    test.error("Timing or total elapsed time not found in " + test.stats)
share = float(timing.group(1)) / float(total.group(1))
if share > MAX_SHARE:
    test.error(f"V3Timing took {share:.0%} of verilation time with {N_CLASSES} classes " +
               f"and {N_DAG} interface classes (over {MAX_SHARE:.0%})")

test.passes()
