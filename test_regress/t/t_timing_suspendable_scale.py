import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")
if test.have_dev_asan or test.tsan:
    test.skip("Too slow with sanitizers")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# Each class overrides a virtual task calling one shared function, so the function and the
# base task each have one dependent per class in the timing dependency graphs
SIZE_RATIO = 4
SIZE_SMALL = 250
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"// Generated by {test.name}.py\n")
        fh.write("class Base;\n")
        fh.write("  static int cnt;\n")
        fh.write("  static function void log(int i);\n")
        fh.write("    cnt += i;\n")
        fh.write("  endfunction\n")
        fh.write("  virtual task body();\n")
        fh.write("  endtask\n")
        fh.write("endclass\n")
        for i in range(n):
            fh.write(f"class C{i} extends Base;\n")
            fh.write("  virtual task body();\n")
            fh.write(f"    log({i});\n")
            fh.write("    #1;\n")
            fh.write("  endtask\n")
            fh.write("endclass\n")
        fh.write("module t;\n")
        fh.write("  initial begin\n")
        fh.write("    automatic Base b = new;\n")
        fh.write("    b.body();\n")
        fh.write("    $finish;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    test.compile(
        verilator_flags2=["--timing", "--stats", "--debug", "--debugi 0", "--no-debug-check"],
        make_main=False,
        verilator_make_gmake=False)
    return test.op_count_read(test.stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX, r'_timing$')

test.passes()
