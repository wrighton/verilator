import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_property_local_var_dispatch_chain.v"

# A chain of interface classes, each extending the previous, with a method of the same name as
# the virtual method a match item value calls on an object of an unrelated class
N_IFACES = 8192
# The work of lowering the value, linear in the methods of the name it calls
MAX_WORK = 20 * N_IFACES
# Time of the NFA lowering, a fraction of a second if linear in the chain, seconds if not
MAX_SECONDS = 1.0


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_property_local_var_dispatch_chain.py\n")
        fh.write("interface class I0;\n")
        fh.write("  pure virtual function int value(int n);\n")
        fh.write("endclass\n")
        for i in range(1, N_IFACES):
            fh.write(f"interface class I{i} extends I{i - 1};\n")
            fh.write("  pure virtual function int value(int n);\n")
            fh.write("endclass\n")
        fh.write("class B;\n")
        fh.write("  virtual function int value(int n);\n")
        fh.write("    return n + 1;\n")
        fh.write("  endfunction\n")
        fh.write("endclass\n")
        fh.write("module t (input clk, input int n);\n")
        fh.write("  B b = new;\n")
        fh.write("  function automatic int calc(int x);\n")
        fh.write("    return b.value(x);\n")
        fh.write("  endfunction\n")
        fh.write("  property p;\n")
        fh.write("    int v;\n")
        fh.write("    @(posedge clk) (1, v = calc(n)) |=> (v == $past(n) + 1);\n")
        fh.write("  endproperty\n")
        fh.write("  assert property (p);\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--assert", "--timing"])

stats = test.file_contents(test.stats)
work = re.search(r'Assertions, local variable lowering work\s+(\d+)', stats)
nfa = re.search(r'Stage, Elapsed time \(sec\), \d+_assertnfa\s+(\S+)', stats)
if not work or not nfa:
    test.error("Lowering work or time not found in " + test.stats)
if float(nfa.group(1)) > MAX_SECONDS:
    test.error(f"NFA lowering took {nfa.group(1)} s with {N_IFACES} interface classes")
if int(work.group(1)) > MAX_WORK:
    test.error(f"Lowering work {work.group(1)} with {N_IFACES} interface classes" +
               f" (over {MAX_WORK})")

test.passes()
