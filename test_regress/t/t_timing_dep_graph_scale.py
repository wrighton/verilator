import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_timing_dep_graph_scale.v"

# Every class overrides a virtual task calling one shared function, so the shared function
# and the base task each have N dependents in the timing dependency graphs; every module
# calls one shared static function
N = 2000


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_timing_dep_graph_scale.py\n")
        fh.write("class Base;\n")
        fh.write("  static int cnt;\n")
        fh.write("  static function int log(int i);\n")
        fh.write("    cnt += i;\n")
        fh.write("    return cnt;\n")
        fh.write("  endfunction\n")
        fh.write("  virtual task body();\n")
        fh.write("  endtask\n")
        fh.write("endclass\n")
        for i in range(n):
            fh.write(f"class C{i} extends Base;\n")
            fh.write("  virtual task body();\n")
            fh.write(f"    void'(log({i}));\n")
            fh.write("    #1;\n")
            fh.write("  endtask\n")
            fh.write("endclass\n")
        for i in range(n):
            fh.write(f"module m{i} (input int a, output int y);\n")
            fh.write("  assign y = Base::log(a);\n")
            fh.write("endmodule\n")
        fh.write("module t;\n")
        fh.write("  int a;\n")
        for i in range(n):
            fh.write(f"  int y{i};\n")
            fh.write(f"  m{i} u{i} (.a(a), .y(y{i}));\n")
        fh.write("  initial begin\n")
        fh.write("    Base b;\n")
        for i in range(0, n, n // 8):
            fh.write(f"    begin automatic C{i} c = new; b = c; b.body(); end\n")
        fh.write("    $finish;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename, N)

test.lint(verilator_flags2=["--timing", "--stats"])

# Linear in N; removing transitive edges from the graphs took time quadratic in N
test.file_grep(test.stats, r'Timing, dependency edges\s+(\d+)', 26032)
test.file_grep(test.stats, r'Timing, dependency edges visited\s+(\d+)', 12024)

test.passes()
