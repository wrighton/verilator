import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# Chains of assignments each adding a constant to, or appending a constant to, the previous
# one. Folding the constants should take one fold per assignment, not one per pair.
SIZE_RATIO = 4
SIZE_SMALL = 200
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write(
            "module t (input logic [31:0] i, output logic [31:0] s, output logic [%d:0] c);\n" %
            (8 + 2 * (n - 1) - 1))
        fh.write("  logic [31:0] s0;\n")
        fh.write("  assign s0 = i;\n")
        fh.write("  logic [7:0] c0;\n")
        fh.write("  assign c0 = i[7:0];\n")
        for k in range(1, n):
            fh.write("  logic [31:0] s%d;\n" % k)
            fh.write("  assign s%d = s%d + 32'd%d;\n" % (k, k - 1, k))
            fh.write("  logic [%d:0] c%d;\n" % (8 + 2 * k - 1, k))
            fh.write("  assign c%d = {c%d, 2'b10};\n" % (k, k - 1))
        fh.write("  assign s = s%d;\n" % (n - 1))
        fh.write("  assign c = c%d;\n" % (n - 1))
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    test.file_cache_clear()
    test.file_grep(test.stats,
                   r'Optimizations, DFG, Peephole, fold assoc binary lhs of rhs\s+(\d+)', n - 2)
    test.file_grep(test.stats,
                   r'Optimizations, DFG, Peephole, fold assoc binary rhs of lhs\s+(\d+)', n - 2)
    return test.op_count_read(test.stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX, r'.*')

test.passes()
