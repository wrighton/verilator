# The --lib-create delay check of many calls of a virtual method overridden in many classes visits
# each class once, not once per call

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_lib_create_timing_virtual_scale.sv"

N_CLASSES = 200
N_CALLS = 200

with open(test.top_filename, 'w', encoding="utf8") as fh:
    fh.write("// Generated by t_lib_create_timing_virtual_scale.py\n")
    fh.write("class Base;\n  virtual function int f(int x);\n    return x;\n  endfunction\n")
    # A delay the library never runs, kept by -fno-dead-methods
    fh.write("  task never();\n    #10;\n  endtask\nendclass\n")
    for i in range(N_CLASSES):
        fh.write(f"class D{i} extends Base;\n  virtual function int f(int x);\n")
        fh.write(f"    return x + {i};\n  endfunction\nendclass\n")
    fh.write("module blk (input int a, output int y);\n  Base b;\n  initial begin\n")
    fh.write("    automatic D0 d = new;\n    b = d;\n  end\n  always_comb begin\n    y = 0;\n")
    for i in range(N_CALLS):
        fh.write(f"    y += b.f(a + {i});\n")
    fh.write("  end\nendmodule\n")

test.compile(verilator_flags2=[
    "--lib-create", "blk", "--top-module", "blk", "--timing", "--stats", "-fno-dead-methods",
    "-fno-inline-funcs"
],
             verilator_make_gmake=False,
             verilator_make_gcc=False,
             make_main=False)

test.file_grep(test.stats, r'Timing, lib-create delay check, override class visits\s+(\d+)',
               N_CLASSES)

test.passes()
