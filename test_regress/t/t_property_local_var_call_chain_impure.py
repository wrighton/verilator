import re

import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_asan or test.tsan:
    test.skip("Too deep a call chain for the stack with sanitizers")

test.top_filename = test.obj_dir + "/t_property_local_var_call_chain_impure.v"

# A chain of functions, each calling the previous, the first calling an imported function not
# declared pure, with a guarded property calling each, found from the last function of the chain
N_FUNCS = 4000
# The work of finding what the values do, linear in the functions and calls
MAX_WORK = 30 * N_FUNCS
# Variables written by a function, more than are told apart, so taken as feeding back
N_WIDE = 1025


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_property_local_var_call_chain_impure.py\n")
        fh.write("module t (input clk, input int x);\n")
        fh.write('  import "DPI-C" function int observe(int n);\n')
        for i in range(N_FUNCS):
            body = f"f{i - 1}(n)" if i else "observe(n)"
            fh.write(f"  function automatic int f{i}(int n);\n")
            fh.write("    /* verilator no_inline_task */\n")
            fh.write(f"    return {body};\n")
            fh.write("  endfunction\n")
        for i in reversed(range(N_FUNCS)):
            fh.write(f"  property p{i};\n")
            fh.write("    int v;\n")
            fh.write(f"    @(posedge clk) (x[0], v = f{i}(x)) |-> (v == x);\n")
            fh.write("  endproperty\n")
            fh.write(f"  assert property (p{i});\n")
        for i in range(N_WIDE):
            fh.write(f"  int w{i};\n")
        fh.write("  function automatic int wide(int n);\n")
        for i in range(N_WIDE):
            fh.write(f"    w{i} = n;\n")
        fh.write("    return n;\n")
        fh.write("  endfunction\n")
        fh.write("  // verilator lint_off SIDEEFFECT\n")
        fh.write("  property p_wide;\n")
        fh.write("    int v;\n")
        fh.write("    @(posedge clk) (1, v = wide(x)) |-> (v == x);\n")
        fh.write("  endproperty\n")
        fh.write("  // verilator lint_on SIDEEFFECT\n")
        fh.write("  assert property (p_wide);\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--assert"])

test.file_grep(test.stats, r'Assertions, local variable state summaries over limit\s+(\d+)', 1)

stats = test.file_contents(test.stats)
work = re.search(r'Assertions, local variable lowering work\s+(\d+)', stats)
if not work:
    test.error("Lowering work not found in " + test.stats)
if int(work.group(1)) > MAX_WORK:
    test.error(f"Lowering work {work.group(1)} with {N_FUNCS} functions (over {MAX_WORK})")

test.passes()
