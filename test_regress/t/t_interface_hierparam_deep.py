import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/" + test.name + ".v"


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("// A chain of hierarchical interface port actuals deeper than resolved\n")
        fh.write("`define stop $stop\n")
        fh.write("`define checkh(gotv,expv) do if ((gotv) !== (expv)) begin $write(\"%%Error: %s:%0d:"
                 "  got='h%x exp='h%x\\n\", `__FILE__,`__LINE__, (gotv), (expv)); `stop; end while(0)\n")
        fh.write("interface bus_if #(parameter int W = 7);\n")
        fh.write("  logic [W-1:0] a;\n")
        fh.write("endinterface\n")
        fh.write("module relay (bus_if src);\n")
        fh.write("  bus_if out ();\n")
        fh.write("endmodule\n")
        fh.write("module chk (bus_if bus);\n")
        fh.write("  if ($bits(bus.a) != 9) begin : g_bad\n")
        fh.write("    $error(\"Wrong interface parameters in generate condition\");\n")
        fh.write("  end\n")
        fh.write("endmodule\n")
        fh.write("module chain #(parameter int K = 0);\n")
        fh.write("  localparam int L0 = K;\n")
        for i in range(1, n):
            fh.write("  localparam int L" + str(i) + " = L" + str(i - 1) + " + 1;\n")
        fh.write("  bus_if #(.W(L" + str(n - 1) + " - " + str(n - 9) + ")) out ();\n")
        fh.write("endmodule\n")
        fh.write("module t;\n")
        fh.write("  chk s (.bus(c.out));\n")
        fh.write("  chain #(.K(1)) c ();\n")
        fh.write("  relay r0 (.src(r1.out));\n")
        for i in range(1, n):
            fh.write("  relay r" + str(i) + " (.src(r" + str(i + 1) + ".out));\n")
        fh.write("  relay r" + str(n) + " (.src(b));\n")
        fh.write("  bus_if b ();\n")
        fh.write("  initial begin\n")
        fh.write("    `checkh($bits(r0.out.a), 7);\n")
        fh.write("    `checkh($bits(c.out.a), 9);\n")
        fh.write('    $write("*-* All Finished *-*\\n");\n')
        fh.write("    $finish;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


# Deeper than the copies V3Param specializes within each other, and than resolving each in turn
# could within the stack of a sanitizer build, with a chain of parameters evaluated in turn
gen(test.top_filename, 600)

test.compile(verilator_flags2=['--binary'])

test.execute()

test.passes()
