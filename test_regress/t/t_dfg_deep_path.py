import os
import re

import vltest_bootstrap

test.scenarios('vlt')

# Sanitizer and debug compiler stack frames are larger, so other passes recursing along the path
# (DfgCseHash::vertexHash, V3Gate unused logic marking, V3Graph ordering,
# V3Sched replication) overflow
if (test.have_dev_asan or test.tsan
        or re.search(r'--debug(\s|$)', ' '.join(test.driver_verilator_flags))
        or os.environ.get('VERILATOR_BIN', '').endswith('_dbg')):
    test.skip("Too deep with sanitizers or the debug compiler")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# always_comb blocks updating a variable many times, giving dataflow paths
# longer than recursion along them can go on the default stack
N_ACYCLIC = 16000
N_CYCLIC = 30000
N_DEAD = 32000
TERMS = ("i", "(i >> 5)", "(i << 7)", "(i * 3)", "{i[31:0], i[63:32]}", "(i >> 9)", "(i << 11)",
         "(i * 5)", "(i >> 13)", "(i << 15)", "(i * 7)", "(i >> 17)", "(i << 19)")
OPS = ("+", "^", "-")

expr = "((a << 1) ^ (a >> 3))"
for n, term in enumerate(TERMS):
    expr = "(%s %s %s)" % (expr, OPS[n % len(OPS)], term)

with open(test.top_filename, 'w', encoding="utf8") as fh:
    fh.write("// Generated by " + test.name + ".py\n")
    fh.write("module t (input logic [63:0] i, output logic [63:0] o, output logic [63:0] p,\n")
    fh.write("          output logic [63:0] q);\n")
    # Acyclic path
    fh.write("  logic [63:0] a;\n")
    fh.write("  always_comb begin\n")
    fh.write("    a = i;\n")
    for _ in range(N_ACYCLIC):
        fh.write("    a = %s;\n" % expr)
    fh.write("  end\n")
    fh.write("  assign o = a;\n")
    # Cyclic path, as each bit of 'c' depends only on lower bits of 'c'
    fh.write("  logic [63:0] c;\n")
    fh.write("  logic [63:0] r;\n")
    fh.write("  assign r = {c[62:0], i[0]};\n")
    fh.write("  always_comb begin\n")
    fh.write("    c = r;\n")
    for _ in range(N_CYCLIC):
        fh.write("    c = (((c << 1) + i) ^ (c << 3)) - (i * 3);\n")
    fh.write("  end\n")
    fh.write("  assign p = c;\n")
    # Two equal paths, which become unused when combined, as 'q' is always zero
    for name in ("d", "e"):
        fh.write("  logic [63:0] %s;\n" % name)
        fh.write("  always_comb begin\n")
        fh.write("    %s = i;\n" % name)
        for _ in range(N_DEAD):
            fh.write("    {0} = ({0} + i) ^ ({0} << 1);\n".format(name))
        fh.write("  end\n")
    fh.write("  assign q = d ^ e;\n")
    fh.write("endmodule\n")

# Run with the default stack limit, and only verilate, as the C++ is large
test.compile(verilator_flags2=['--no-unlimited-stack'], verilator_make_gmake=False)

test.passes()
