import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_hier_block_param_stub_scale.v"

# A parameterized hierarchical block with many parameters and many ranged enumerations,
# none of which keep it from being stubbed
SIZE_RATIO = 4
SIZE_SMALL = 500
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_hier_block_param_stub_scale.py\n")
        fh.write("module sub #(parameter int P = 0) (output logic [6:0] q);\n")
        fh.write("  /*verilator hier_block*/\n")
        for i in range(n):
            fh.write(f"  localparam int k{i} = P + {i};\n")
            fh.write(f"  enum int {{e{i}x[1] = 0}} d{i};\n")
        fh.write(f"  assign q = 7'(k{n - 1});\n")
        fh.write("endmodule\n")
        # The library of the block, as --hierarchical-block names it
        fh.write("module sub_17 (output logic [6:0] q);\n")
        fh.write("  assign q = '0;\n")
        fh.write("endmodule\n")
        fh.write("module t (output logic [6:0] q);\n")
        fh.write("  sub #(.P(17)) u_sub (.q(q));\n")
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    # As the run of the top of a hierarchical Verilation, in one process for operation counts
    test.lint(verilator_flags2=[
        "--hierarchical-block sub,sub_17,P,17", "--top-module t", "--stats", "--debug",
        "--debugi 0", "--no-debug-check"
    ])
    stats = test.obj_dir + "/" + test.vm_prefix + "__hier.dir/" + test.vm_prefix + "__stats.txt"
    test.file_grep(stats, r'LinkCells, Hierarchical blocks stubbed\s+(\d+)', 1)
    return test.op_count_read(stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX, r'.*')

test.passes()
