import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_dfg_peephole_mem_scale.v"

# One always_comb with N_BITS conditional single bit writes into one vector. DFG peephole
# rewrites the selects of the chain of updated values about N_BITS**2 / 2 times, each creating
# a vertex. The model is not built.
N_BITS = 1000
# Growth of peak memory in DFG peephole (about 0.2 MB when linear; 47 MB when quadratic, of
# which 13 MB is removed entries kept in the iteration list)
MAX_GROWTH_MB = 4


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_dfg_peephole_mem_scale.py\n")
        fh.write(f"module t (input [{N_BITS - 1}:0] sel, input [{N_BITS - 1}:0] a,\n")
        fh.write(f"          output logic [{N_BITS - 1}:0] v);\n")
        fh.write("  always_comb begin\n")
        fh.write("    v = '0;\n")
        for i in range(N_BITS):
            fh.write(f"    if (sel[{i}]) v[{i * 7 % N_BITS}] = a[{i}];\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.compile(verilator_flags2=["--stats"], make_main=False, verilator_make_gmake=False)

# Peak memory after each stage, in stage order
peaks = re.findall(r'Stage, Memory peak \(MB\), \d+_(\S+)\s+(\S+)', test.file_contents(test.stats))
growth = 0.0
for i, (stage, peak) in enumerate(peaks):
    if stage == "dfg-peephole":
        growth += float(peak) - float(peaks[i - 1][1])
if not any(stage == "dfg-peephole" for stage, _ in peaks):
    test.error("DFG peephole stage not found in " + test.stats)
print(f"Peak memory growth in DFG peephole with {N_BITS} bits: {growth:.1f} MB")
# With AddressSanitizer, peak memory also holds freed memory in its quarantine, so the limit
# applies only without it; Verilator is still checked for memory errors and leaks
if growth > MAX_GROWTH_MB and not test.have_dev_asan:
    test.error(f"Peak memory grew {growth:.1f} MB in DFG peephole with {N_BITS} bits " +
               f"(over {MAX_GROWTH_MB} MB)")

test.passes()
