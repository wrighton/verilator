import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_sched_virtual_call_scale.v"

# Every class overrides a virtual task, and a process calls it N_CLASSES times, so each call site
# may call N_CLASSES functions. Each override calls a task awaiting N_EVENTS events
N_CLASSES = 1000
N_EVENTS = 300
# Share of verilation time spent in V3Delayed (about 0.02 when linear, 0.45 when quadratic)
MAX_SHARE = 0.1
# Ignore a high share of a short time, e.g. from a load spike (quadratic takes about 1 s)
MIN_SECONDS = 0.2


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_sched_virtual_call_scale.py\n")
        fh.write("package p;\n")
        for i in range(N_EVENTS):
            fh.write(f"  event e{i};\n")
        fh.write("endpackage\n")
        fh.write("class W;\n")
        fh.write("  static task run(int i);\n")
        for i in range(N_EVENTS):
            fh.write(f"    if (i == {i}) @(p::e{i});\n")
        fh.write("  endtask\n")
        fh.write("endclass\n")
        fh.write("class Base;\n")
        fh.write("  virtual task body();\n")
        fh.write("  endtask\n")
        fh.write("endclass\n")
        for i in range(N_CLASSES):
            fh.write(f"class C{i} extends Base;\n")
            fh.write("  virtual task body();\n")
            fh.write(f"    W::run({i % N_EVENTS});\n")
            fh.write("  endtask\n")
            fh.write("endclass\n")
        fh.write("module t;\n")
        fh.write("  initial begin\n")
        fh.write("    Base b;\n")
        for i in range(N_CLASSES):
            fh.write(f"    begin automatic C{i} c = new; b = c; b.body(); end\n")
        fh.write("    $finish;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.compile(verilator_flags2=["--timing", "--stats"],
             make_main=False,
             verilator_make_gmake=False)

stats = test.file_contents(test.stats)
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
delayed = re.search(r'Stage, Elapsed time \(sec\), \d+_delayed\s+(\S+)', stats)
if not total or not delayed:
    test.error("Stage elapsed times not found in " + test.stats)
seconds = float(delayed.group(1))
share = seconds / float(total.group(1))
if seconds > MIN_SECONDS and share > MAX_SHARE:
    test.error(f"V3Delayed took {share:.0%} of verilation time with {N_CLASSES} classes (over " +
               f"{MAX_SHARE:.0%})")

test.passes()
