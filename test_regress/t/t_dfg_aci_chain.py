import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# A chain of assignments each OR-ing one of a few masks into the previous one, with each mask
# repeated over a run of assignments. Removing the repeated masks should take work linear in
# the length of the chain.
SIZE_RATIO = 4
SIZE_SMALL = 200
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
N_MASKS = 8
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("module t (input logic [31:0] i, output logic [31:0] o);\n")
        fh.write("  logic [31:0] o0;\n")
        fh.write("  assign o0 = i;\n")
        for k in range(1, n):
            fh.write("  logic [31:0] o%d;\n" % k)
            fh.write("  assign o%d = o%d | (32'd1 << %d);\n" % (k, k - 1, k // (n // N_MASKS)))
        fh.write("  assign o = o%d;\n" % (n - 1))
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    test.file_cache_clear()
    # Each assignment but the first of each run of a mask is removed as a repeat, and the
    # masks of the runs are folded into one constant
    test.file_grep(test.stats,
                   r'Optimizations, DFG, Peephole, fold assoc binary lhs of rhs\s+(\d+)',
                   N_MASKS - 1)
    test.file_grep(test.stats, r'Optimizations, DFG, Peephole, remove aci binary rhs\s+(\d+)',
                   n - 1 - N_MASKS)
    return test.op_count_read(test.stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX,
                 r'dfg-peephole')

test.passes()
