import re

import vltest_bootstrap

test.scenarios('vltmt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")
if test.have_dev_asan or test.tsan:
    test.skip("Too slow with sanitizers")

test.top_filename = test.obj_dir + "/t_order_pipeline_mt_scale.v"

# Pipelines of stages, each stage a separate process reading the previous one, so the
# multi-threaded scheduler builds long chains of MTasks. Four pipelines give two threads enough
# parallelism. Only measures scheduling time, the model is not built.
PIPELINES = 4
SIZE_SMALL = 500
SIZE_LARGE = SIZE_SMALL * 8
# Linear scaling gives 8x, quadratic gives 64x
MAX_RATIO = 40
# Ignore the ratio when scheduling is fast enough that timer noise dominates
MIN_SECONDS = 0.25


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_order_pipeline_mt_scale.py\n")
        fh.write(f"module t (input clk, input int d, output int q[{PIPELINES}]);\n")
        for p in range(PIPELINES):
            fh.write(f"  int r{p}_0;\n")
            fh.write(f"  always_ff @(posedge clk) r{p}_0 <= d + {p};\n")
            for i in range(1, n):
                fh.write(f"  int r{p}_{i};\n")
                fh.write(f"  always_ff @(posedge clk) r{p}_{i} <= r{p}_{i - 1} + {i};\n")
            fh.write(f"  assign q[{p}] = r{p}_{n - 1};\n")
        fh.write("endmodule\n")


def sched_seconds(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--no-debug-check"],
                 threads=2,
                 make_main=False,
                 verilator_make_gmake=False)
    with open(test.stats, 'r', encoding="utf8") as fh:
        times = re.findall(r'Stage, Elapsed time \(sec\), \d+_sched-create-\w+\s+(\S+)', fh.read())
    if not times:
        test.error("Scheduling elapsed time not found in " + test.stats)
    return sum(float(t) for t in times)


small = sched_seconds(SIZE_SMALL)
large = sched_seconds(SIZE_LARGE)
print(f"{SIZE_SMALL} stages took {small:.3f}s, {SIZE_LARGE} took {large:.3f}s")
if large > MIN_SECONDS and large > small * MAX_RATIO:
    test.error("Multi-threaded scheduling time scaled superlinearly with pipeline stages: " +
               f"{SIZE_SMALL} stages took {small:.3f}s, " +
               f"{SIZE_LARGE} stages took {large:.3f}s (over {MAX_RATIO}x)")

test.passes()
