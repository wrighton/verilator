import re

import vltest_bootstrap

test.scenarios('vlt')

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# Local variables assigned inside, or before and inside, nested 'intersect', 'and' and 'or'
# operators, nested in the right or in the left operand, the other operand assigning a variable or
# not. Only measures the lowering of the local variables, the model is not built.
SIZE_RATIO = 4
SIZE_SMALL = 25
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
# The work is bounded by n log n, giving 5.7x for 4x the size; quadratic work gives 16x
RATIO_MAX = 7
SHAPES = ("right", "before", "left", "both")


def gen(filename, shape, n):
    assigns = "".join(f", x{i} = cyc" for i in range(n))
    nest = f"(a intersect (1'b1{assigns}))"
    for i in range(n - 1):
        op = 'and' if i < n // 2 else 'or'
        if shape == "left":
            nest = f"({nest} {op} a)"
        elif shape == "both":
            nest = f"({nest} {op} (1'b1, x{i} = cyc))"
        else:
            nest = f"(a {op} {nest})"
    before = f"(1'b1{assigns}) ##1 " if shape == "before" else ""
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("module t (input clk, input a, input int cyc);\n")
        fh.write("  property p;\n")
        fh.write("    int " + ", ".join(f"x{i}" for i in range(n)) + ";\n")
        fh.write(f"    @(posedge clk) {before}{nest} ##1 a;\n")
        fh.write("  endproperty\n")
        fh.write("  assert property (p);\n")
        fh.write("endmodule\n")


def flow_entries(shape, n):
    gen(test.top_filename, shape, n)
    test.lint(verilator_flags2=["--stats"])
    with open(test.stats, 'r', encoding="utf8") as fh:
        match = re.search(r'Assertions, local variable flow entries\s+(\d+)', fh.read())
    if not match:
        test.error("Flow entries not found in " + test.stats)
    return int(match.group(1))


for shape in SHAPES:
    small = flow_entries(shape, SIZE_SMALL)
    large = flow_entries(shape, SIZE_LARGE)
    if large > small * RATIO_MAX:
        test.error(f"Flow entries of {shape} nesting scale by {large / small:0.2f},"
                   f" {small} to {large}")

test.passes()
