import re

import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")
if test.have_dev_asan or test.tsan:
    test.skip("Too slow with sanitizers")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# An unpacked struct of byte members streamed to a vector, which reaches V3Expand as
# assignments of eight members at a time to constant selects of the vector. Only measures
# V3Expand time, the model is not built.
SIZE_SMALL = 2048
SIZE_LARGE = SIZE_SMALL * 4
# Linear scaling gives 4x, quadratic gives 16x
MAX_RATIO = 8
# Ignore the ratio when V3Expand is fast enough that timer noise dominates
MIN_SECONDS = 0.1


def gen(filename, n):
    members = "".join(f"    logic [7:0] m{i};\n" for i in range(n))
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"""// Generated by {test.name}.py
module t (output logic [{8 * n - 1}:0] q);
  typedef struct {{
{members}  }} s_t;
  s_t s;
  initial q = {{>>{{s}}}};
endmodule
""")


def expand_seconds(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    with open(test.stats, 'r', encoding="utf8") as fh:
        stats = fh.read()
    selects = re.search(r'Optimizations, Expand, pattern assign to sel const wide\s+(\d+)', stats)
    expand = re.search(r'Stage, Elapsed time \(sec\), \d+_expand\s+(\S+)', stats)
    if not selects or not expand:
        test.error("Expanded selects or expand elapsed time not found in " + test.stats)
    if int(selects.group(1)) != n // 8:
        test.error(f"Expanded {selects.group(1)} assignments to selects, expected {n // 8}")
    return float(expand.group(1))


small = expand_seconds(SIZE_SMALL)
large = expand_seconds(SIZE_LARGE)
if large > MIN_SECONDS and large > small * MAX_RATIO:
    test.error("V3Expand time scaled superlinearly with members: " +
               f"{SIZE_SMALL} members took {small:.3f}s, " +
               f"{SIZE_LARGE} members took {large:.3f}s (over {MAX_RATIO}x)")

test.passes()
