import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_opt_split_decoder_scale.v"

# Case items writing a different variable each. V3Case makes them a long if/else chain, which
# V3Split must not copy for each variable. Only measures V3Split, the model is not built.
SIZE_SMALL = 2000
SIZE_LARGE = SIZE_SMALL * 4
# Linear scaling gives 4x, quadratic gives 16x
MAX_RATIO = 8
# Ignore the ratio when V3Split is fast enough that timer noise dominates
MIN_SECONDS = 0.25


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_opt_split_decoder_scale.py\n")
        fh.write("module t (input clk, input we, input int addr, input int wdata,\n")
        fh.write("          output int " + ", ".join(f"q{i}" for i in range(n)) + ");\n")
        fh.write("  always_ff @(posedge clk) begin\n")
        fh.write("    if (we) begin\n")
        fh.write("      case (addr)\n")
        for i in range(n):
            fh.write(f"        {i * 4}: q{i} <= wdata + {i};\n")
        fh.write("        default: ;\n")
        fh.write("      endcase\n")
        fh.write("    end\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def split_seconds(n):
    gen(test.top_filename, n)
    # Disable other passes that are slow on this code, to keep the test fast
    test.compile(verilator_flags2=[
        "--stats", "--no-debug-check", "-fno-dfg", "-fno-life", "-fno-merge-cond", "-fno-reloop"
    ],
                 make_main=False,
                 verilator_make_gmake=False)
    with open(test.stats, 'r', encoding="utf8") as fh:
        stats = fh.read()
    declined = re.search(r'Optimizations, Split always declined as too large\s+(\d+)', stats)
    if not declined or declined.group(1) != "1":
        test.error("Splitting the decoder was not declined in " + test.stats)
    times = re.findall(r'Stage, Elapsed time \(sec\), \d+_split\s+(\S+)', stats)
    if not times:
        test.error("Split elapsed time not found in " + test.stats)
    return sum(float(t) for t in times)


small = split_seconds(SIZE_SMALL)
large = split_seconds(SIZE_LARGE)
if large > MIN_SECONDS and large > small * MAX_RATIO:
    test.error("V3Split time scaled superlinearly with case items: " +
               f"{SIZE_SMALL} items took {small:.3f}s, " +
               f"{SIZE_LARGE} items took {large:.3f}s (over {MAX_RATIO}x)")

test.passes()
