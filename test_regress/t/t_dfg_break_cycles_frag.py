import vltest_bootstrap

test.scenarios('vlt')

if test.have_dev_gcov:
    test.skip("Too slow with code coverage")

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# A vector whose even bits form a chain driven from their own lower bits, and whose odd bits
# depend on a cycle through the top bit, so each even bit is a separate independent range.
# Tracing the drivers of all of them should visit vertices linear in the width.
SIZE_SMALL = 250
SIZE_LARGE = 1000
VERTICES_TRACED = {SIZE_SMALL: 996, SIZE_LARGE: 3996}
SINKS_EXAMINED = {SIZE_SMALL: 5633, SIZE_LARGE: 26494}


def gen(filename, n):
    terms = []
    for k in range(n):
        if k == 0:
            terms.append("i[0]")
        elif k == n - 1:
            terms.append(f"^v[{n - 2}:0]")
        elif k % 2 == 0:
            terms.append(f"(v[{k - 2}] ^ i[{k % 64}])")
        else:
            terms.append(f"(v[{n - 1}] ^ i[{k % 64}])")
    body = ",\n    ".join(reversed(terms))
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write(f"""// Generated by {test.name}.py
module t (input logic [63:0] i, output logic [63:0] o);
  // verilator lint_off UNOPTFLAT
  logic [{n - 1}:0] v;
  // verilator lint_on UNOPTFLAT
  assign v = {{
    {body}}};
  assign o = v[{n - 1}:{n - 64}];
endmodule
""")


def verilation(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats"], make_main=False, verilator_make_gmake=False)
    test.file_cache_clear()
    test.file_grep(test.stats, r'Optimizations, DFG, BreakCycles, changes applied\s+(\d+)', n // 2)
    test.file_grep(test.stats, r'Optimizations, DFG, BreakCycles, vertices traced\s+(\d+)',
                   VERTICES_TRACED[n])
    test.file_grep(test.stats, r'Optimizations, DFG, BreakCycles, sinks examined\s+(\d+)',
                   SINKS_EXAMINED[n])


verilation(SIZE_SMALL)
verilation(SIZE_LARGE)

test.passes()
