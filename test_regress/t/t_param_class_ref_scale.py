import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_param_class_ref_scale.v"

# Many modules, each calling a method of a class, whose class V3Param looks for from each call
SIZE_RATIO = 4
SIZE_SMALL = 200
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 6  # Linear scaling gives 4x, the quadratic walk 8x already at these sizes


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_param_class_ref_scale.py\n")
        fh.write("package pkg;\n  class C;\n")
        fh.write("    static function int f(int x);\n      return x + 1;\n    endfunction\n")
        fh.write("  endclass\nendpackage\n")
        for i in range(n):
            fh.write(f"module m{i} (input int a, output int y);\n")
            fh.write("  assign y = pkg::C::f(a);\nendmodule\n")
        fh.write(f"module t (input int a, output int y[{n}]);\n")
        for i in range(n):
            fh.write(f"  m{i} u{i} (.a, .y(y[{i}]));\n")
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    test.lint(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"])
    return test.op_count_read(test.stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX,
                 r'\d+_param$')

test.passes()
