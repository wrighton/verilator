import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_begin_nested_scale.v"

# Named blocks nested n deep, with names of the same length. The scopes of the blocks are built by
# appending each block's name once, so linear in n, not copied for each block, quadratic in n.
SIZE_SMALL = 100
SIZE_LARGE = SIZE_SMALL * 4


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_begin_nested_scale.py\n")
        fh.write("module t;\n")
        fh.write("  logic q;\n")
        fh.write("  initial begin\n")
        for i in range(n):
            fh.write(f"    begin : b{i:04d}\n")
        fh.write("    q = 1;\n")
        for i in range(n):
            fh.write("    end\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats"], make_main=False, verilator_make_gmake=False)
    test.file_cache_clear()
    # Each of the three scopes gets each 5 character name, and a '__DOT__' before all but the first
    test.file_grep(test.stats, r'Begin, scope characters appended\s+(\d+)',
                   3 * 5 * n + 3 * 7 * (n - 1))


verilation(SIZE_SMALL)
verilation(SIZE_LARGE)

test.passes()
