import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_param_class_ref_chain_scale.v"

# Each class has a member referring to the next one, in a chain of N_CHAIN classes
N_CHAIN = 3000
# Memory growth in V3Param, as a share of the memory used before (about 0.05 when linear, 2.3
# when each class is named after the chain of references to it)
MAX_GROWTH = 0.5


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_param_class_ref_chain_scale.py\n")
        for i in reversed(range(N_CHAIN)):
            fh.write(f"class C{i};\n")
            fh.write("  int v;\n")
            if i + 1 < N_CHAIN:
                fh.write(f"  C{i + 1} nxt;\n")
            fh.write("endclass\n")
        fh.write("module t;\n")
        fh.write("  initial begin\n")
        fh.write("    automatic C0 c = new;\n")
        fh.write("    c.v = 1;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--no-debug-check"])

memories = re.findall(r'Stage, Memory current \(MB\), \d+_(\S+)\s+(\S+)',
                      test.file_contents(test.stats))
names = [name for name, _ in memories]
if 'param' not in names:
    test.error("Stage statistics not found in " + test.stats)

# Memory statistics are zero where the OS does not report them
i = names.index('param')
before = float(memories[i - 1][1])
growth = (float(memories[i][1]) - before) / before if before else 0
if growth > MAX_GROWTH:
    test.error(f"Memory grew by {growth:.0%} in V3Param (over {MAX_GROWTH:.0%})")

test.passes()
