import re

import vltest_bootstrap

test.scenarios('vlt')

test.top_filename = test.obj_dir + "/" + test.name + ".v"

# An if/else-if chain whose branches write different variables, so V3MergeCond sees deeply
# nested statements, each with its own variables. Only measures V3MergeCond, the model is not
# built.
SIZE_SMALL = 200
SIZE_LARGE = SIZE_SMALL * 4
# Linear scaling gives 4x, quadratic gives 16x
MAX_RATIO = 8


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("module t (input clk, input int sel, input int a, output int q[8]);\n")
        fh.write("  always_ff @(posedge clk) begin\n")
        for i in range(n):
            fh.write("    " + ("if" if i == 0 else "else if") + f" (sel == {i * 7}) begin\n")
            fh.write(f"      q[{i % 8}] <= a + {i};\n")
            fh.write(f"      q[{(i + 3) % 8}] <= a - {i};\n")
            fh.write("    end\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def gen_wide(filename, n):
    # A condition of many variables, followed by assignments to other variables
    def tree(lo, hi):
        if hi - lo == 1:
            return f"a{lo}"
        mid = (lo + hi) // 2
        return f"({tree(lo, mid)} || {tree(mid, hi)})"

    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by " + test.name + ".py\n")
        fh.write("module t (input clk, input int x, output int q[" + str(n) + "],\n")
        fh.write("          input bit " + ", ".join(f"a{i}" for i in range(n)) + ");\n")
        fh.write("  always_ff @(posedge clk) begin\n")
        fh.write(f"    if ({tree(0, n)}) q[0] <= x + 1;\n")
        for i in range(1, n):
            fh.write(f"    q[{i}] <= x;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def variable_entries(generator, n, expected):
    generator(test.top_filename, n)
    # Disable other passes that are slow on this code, to keep the test fast
    test.compile(verilator_flags2=["--stats", "-fno-dfg", "-fno-reloop", "-fno-split"],
                 make_main=False,
                 verilator_make_gmake=False)
    with open(test.stats, 'r', encoding="utf8") as fh:
        match = re.search(r'Optimizations, MergeCond variable entries\s+(\d+)', fh.read())
    if not match:
        test.error("MergeCond variable entries not found in " + test.stats)
    if int(match.group(1)) != expected:
        test.error(f"MergeCond variable entries for {n} items: got {match.group(1)}," +
                   f" expected {expected}")
    return int(match.group(1))


def check_scaling(generator, small_expected, large_expected):
    small = variable_entries(generator, SIZE_SMALL, small_expected)
    large = variable_entries(generator, SIZE_LARGE, large_expected)
    if large > small * MAX_RATIO:
        test.error(f"MergeCond variable entries scaled superlinearly in {generator.__name__}: " +
                   f"{SIZE_SMALL} items had {small}, {SIZE_LARGE} items had {large}" +
                   f" (over {MAX_RATIO}x)")


check_scaling(gen, 3511, 13709)
check_scaling(gen_wide, 3711, 14520)

test.passes()
