import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_property_local_var_depth_unsup.v"

# Match item values each calling a virtual method of a class calling the method of the same name
# of another class, and so on, through as many classes as dynamically dispatched calls nest in
# finding what a value does, and one more
DEPTHS = (64, 65)


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_property_local_var_depth_unsup.py\n")
        for depth in DEPTHS:
            fh.write(f"class D{depth}_0;\n")
            fh.write("  virtual function int value(int n); return n + 1; endfunction\n")
            fh.write("endclass\n")
            for i in range(1, depth):
                fh.write(f"class D{depth}_{i};\n")
                fh.write(f"  D{depth}_{i - 1} next;\n")
                fh.write(
                    "  virtual function int value(int n); return next.value(n); endfunction\n")
                fh.write("endclass\n")
        fh.write("module t (input clk, input int n);\n")
        for depth in DEPTHS:
            fh.write(f"  D{depth}_{depth - 1} d{depth};\n")
            fh.write(f"  function automatic int calc{depth}(int x); return d{depth}.value(x);" +
                     " endfunction\n")
            fh.write(f"  property p{depth}; int v; @(posedge clk) (1, v = calc{depth}(n))" +
                     " |=> (v == $past(n) + 1); endproperty\n")
            fh.write(f"  assert property (p{depth});\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--assert", "--timing"],
          fails=True,
          expect_filename=test.golden_filename)

test.passes()
