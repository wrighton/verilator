import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_order_ring_deep.v"

# A ring of registers longer than recursion along it can go on the default stack
N = 40000

with open(test.top_filename, 'w', encoding="utf8") as fh:
    fh.write("// Generated by t_order_ring_deep.py\n")
    fh.write("module t (input clk, output logic o);\n")
    for i in range(N):
        fh.write("  logic r%d;\n" % i)
    fh.write("  always_ff @(posedge clk) r0 <= ~r%d;\n" % (N - 1))
    for i in range(1, N):
        fh.write("  always_ff @(posedge clk) r%d <= r%d;\n" % (i, i - 1))
    fh.write("  assign o = r%d;\n" % (N - 1))
    fh.write("endmodule\n")

# Run with the default stack limit, and only verilate, as the C++ is large
test.compile(verilator_flags2=['--no-unlimited-stack'], verilator_make_gmake=False)

test.passes()
