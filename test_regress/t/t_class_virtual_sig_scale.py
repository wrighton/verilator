import re

import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_class_virtual_sig_scale.v"

# Interface classes I2..I{N_IFACES} each extend the previous two without redeclaring the method,
# so the number of inheritance paths from the implementing class to I0 is exponential
N_IFACES = 32
# Share of verilation time spent in V3WidthCommit (about 0.9 when exponential)
MAX_SHARE = 0.5
# Ignore a high share of a short time, e.g. from a load spike (exponential takes about 0.4 s)
MIN_SECONDS = 0.1


def gen(filename):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_class_virtual_sig_scale.py\n")
        fh.write("interface class I0;\n")
        fh.write("  pure virtual function int f(int i);\n")
        fh.write("endclass\n")
        fh.write("interface class I1 extends I0;\n")
        fh.write("endclass\n")
        for i in range(2, N_IFACES + 1):
            fh.write(f"interface class I{i} extends I{i - 1}, I{i - 2};\n")
            fh.write("endclass\n")
        fh.write(f"class C implements I{N_IFACES};\n")
        fh.write("  virtual function int f(int i);\n")
        fh.write("    return i;\n")
        fh.write("  endfunction\n")
        fh.write("endclass\n")
        fh.write("module t;\n")
        fh.write("  initial begin\n")
        fh.write("    C c;\n")
        fh.write("    I0 i;\n")
        fh.write("    c = new;\n")
        fh.write("    i = c;\n")
        fh.write("    if (i.f(1) != 1) $stop;\n")
        fh.write("    $finish;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


gen(test.top_filename)

test.lint(verilator_flags2=["--stats", "--no-timing"])

stats = test.file_contents(test.stats)
total = re.search(r'Stage, Elapsed time \(sec\), TOTAL\s+(\S+)', stats)
width = re.search(r'Stage, Elapsed time \(sec\), \d+_widthcommit\s+(\S+)', stats)
if not total or not width:
    test.error("Stage elapsed times not found in " + test.stats)
seconds = float(width.group(1))
share = seconds / float(total.group(1))
if seconds > MIN_SECONDS and share > MAX_SHARE:
    test.error(f"V3WidthCommit took {share:.0%} of verilation time with " +
               f"{N_IFACES} interface classes (over {MAX_SHARE:.0%})")

test.passes()
