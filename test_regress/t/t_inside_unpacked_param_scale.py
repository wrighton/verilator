import vltest_bootstrap

test.scenarios('vlt')
test.top_filename = test.obj_dir + "/t_inside_unpacked_param_scale.v"

# A constant 'inside' an unpacked array parameter, folded in one pass over the elements
SIZE_RATIO = 4
SIZE_SMALL = 2000
SIZE_LARGE = SIZE_SMALL * SIZE_RATIO
RATIO_MIN = 3
RATIO_MAX = 8  # Linear scaling gives 4x, quadratic gives 16x


def gen(filename, n):
    with open(filename, 'w', encoding="utf8") as fh:
        fh.write("// Generated by t_inside_unpacked_param_scale.py\n")
        fh.write("module t;\n")
        fh.write(f"  localparam int LIST[{n}] = '{{\n")
        fh.write(",\n".join(f"    {i * 3}" for i in range(n)))
        fh.write("\n  };\n")
        fh.write(f"  localparam bit HIT = {(n - 1) * 3} inside {{LIST}};\n")
        fh.write("  localparam bit MISS = 1 inside {LIST};\n")
        fh.write("  initial begin\n")
        fh.write("    if (HIT != 1) $stop;\n")
        fh.write("    if (MISS != 0) $stop;\n")
        fh.write("  end\n")
        fh.write("endmodule\n")


def verilation(n):
    gen(test.top_filename, n)
    test.compile(verilator_flags2=["--stats", "--debug", "--debugi 0", "--no-debug-check"],
                 make_main=False,
                 verilator_make_gmake=False)
    return test.op_count_read(test.stats)


test.op_count_ok(verilation(SIZE_SMALL), verilation(SIZE_LARGE), RATIO_MIN, RATIO_MAX, r'.*')

test.passes()
